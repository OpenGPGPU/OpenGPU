#ifndef OPENGPU_COMPUTE_IMAGE_DESCRIPTOR_H
#define OPENGPU_COMPUTE_IMAGE_DESCRIPTOR_H
#include "opengpu_compute_texture_records.h"
#include "opengpu_texture_image_format_abi.h"
#include "opengpu_image_format_policy.h"

#define OPENGPU_COMPUTE_IMAGE_DESCRIPTOR_WORDS 64u
#define OPENGPU_COMPUTE_IMAGE_UNITS 4u

/* The shader image path accepts the same thirteen image-unit formats as
 * ShaderImageFormat. Bytes and component width classes are kept separate:
 * a 32-bit single component and four 8-bit components are size-compatible,
 * but are not class-compatible. */
static inline bool opengpu_compute_image_r32(u32 format)
{
    return format == OPENGPU_TEXTURE_FORMAT_R32F ||
           format == OPENGPU_TEXTURE_FORMAT_R32UI ||
           format == OPENGPU_TEXTURE_FORMAT_R32I;
}

struct opengpu_compute_image_descriptor {
    u32 context, pass, generation, unit;
    u32 storage_format, image_format, level, base_level, max_level, layer;
    bool readable, writable, compatible_by_size, layered;
    /* A kernel-owned snapshot. base is an offset in the retained binding. */
    struct opengpu_compute_texture_level_config view;
};

/* Build an immutable GIU1 record for a retained, already-authorized binding.
 * This validates layout and bounds, not backing provenance, cache visibility,
 * permissions on the VM mapping or object lifetime. On failure, leave output
 * untouched. */
static inline bool opengpu_build_compute_image_descriptor(
    u32 out[OPENGPU_COMPUTE_IMAGE_DESCRIPTOR_WORDS],
    const struct opengpu_compute_image_descriptor *d,
    u32 binding_base, unsigned long long binding_size)
{
    u32 result[OPENGPU_COMPUTE_IMAGE_DESCRIPTOR_WORDS] = {0}, scratch[32];
    struct opengpu_compute_texture_level_config view;
    unsigned long long limit = (unsigned long long)binding_base + binding_size;
    unsigned long long base;
    u32 bytes, image_bytes, layers;
    if (!out || !d || !binding_size || binding_size > (1ULL << 32) ||
        limit > (1ULL << 32) || d->unit >= OPENGPU_COMPUTE_IMAGE_UNITS ||
        (!d->readable && !d->writable) || d->level > 15 ||
        d->base_level > d->level || d->level > d->max_level || d->max_level > 15)
        return false;
    bytes = d->view.target == OPENGPU_TEXTURE_BUFFER_TARGET ?
        opengpu_texture_buffer_format_bytes(d->storage_format) : opengpu_compute_image_format_bytes(d->storage_format);
    image_bytes = opengpu_compute_image_format_bytes(d->image_format);
    if (!bytes || bytes != image_bytes ||
        (!d->compatible_by_size && (d->view.target == OPENGPU_TEXTURE_BUFFER_TARGET ?
         opengpu_texture_format_component_class(d->storage_format) != opengpu_texture_format_component_class(d->image_format) :
         (bytes == 4 && opengpu_compute_image_r32(d->storage_format) != opengpu_compute_image_r32(d->image_format)))))
        return false;
    view = d->view;
    if (view.target == OPENGPU_TEXTURE_BUFFER_TARGET &&
        (d->level || d->base_level || d->max_level || d->layered || d->layer))
        return false;
    base = (unsigned long long)binding_base + view.base;
    if (view.base >= binding_size || base >= (1ULL << 32) ||
        view.level != d->level || view.block_4x4 || view.block_bytes != bytes)
        return false;
    view.base = (u32)base;
    view.allocation_base = binding_base;
    view.allocation_limit = limit;
    if (!opengpu_encode_compute_texture_level(scratch, &view))
        return false;
    layers = view.target == 1 ? view.layers : view.target == 2 ? 6 :
             view.target == 3 ? view.depth : 1;
    if ((view.target == 0 && (d->layered || d->layer)) ||
        (!d->layered && d->layer >= layers))
        return false;
    /* GIU1 layout generated by EmitShaderImageAbi. */
    result[0]=0x47495501u; result[1]=256; result[2]=1;
    result[3]=d->context; result[4]=d->pass; result[5]=d->generation;
    result[6]=d->unit; result[7]=1; result[8]=1; result[9]=1u << 2;
    result[10]=d->readable; result[11]=d->writable;
    result[12]=d->storage_format; result[13]=d->image_format;
    result[14]=d->compatible_by_size; result[15]=d->level;
    result[16]=d->base_level; result[17]=d->max_level;
    result[18]=d->layered; result[19]=d->layer;
    result[20]=view.target; result[21]=view.level; result[22]=binding_base;
    result[23]=(u32)limit; result[24]=(u32)(limit >> 32); result[25]=view.base;
    result[26]=view.width; result[27]=view.height; result[28]=view.depth; result[29]=view.layers;
    result[30]=(u32)view.row_pitch; result[31]=(u32)(view.row_pitch >> 32);
    result[32]=(u32)view.slice_pitch; result[33]=(u32)(view.slice_pitch >> 32);
    result[34]=(u32)view.layer_pitch; result[35]=(u32)(view.layer_pitch >> 32);
    result[37]=view.block_bytes;
    result[38]=view.buffer_texels; result[39]=(u32)view.buffer_bytes;
    result[40]=(u32)(view.buffer_bytes >> 32);
    for (u32 i=0; i<OPENGPU_COMPUTE_IMAGE_DESCRIPTOR_WORDS; ++i) out[i]=result[i];
    return true;
}
#endif

package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import opengpu.command.GpuCommandOpcode
import opengpu.graphics.{NativeVisibilityQueryCapabilities => Caps, VisibilityQueryRecord => Record}

object EmitNativeVisibilityQueryAbi {
  def main(args: Array[String]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"), "EmitNativeVisibilityQueryAbi [--check]")
    val checking = args.nonEmpty
    val opcodes = Seq("BEGIN" -> GpuCommandOpcode.queryBegin.litValue,
      "END" -> GpuCommandOpcode.queryEnd.litValue, "POLL" -> GpuCommandOpcode.queryPoll.litValue,
      "RESULT" -> GpuCommandOpcode.queryResult.litValue)
    val fields = Seq("MAGIC" -> 0, "BYTES" -> 1, "CONTEXT" -> 2, "COOKIE" -> 3,
      "FLAGS" -> 4, "VALUE" -> 5, "ROOT" -> 6, "RESERVED" -> 7)
    val constants = Seq("CAPABILITIES" -> s"0x${Caps.base.toHexString}u",
      "CAPABILITY_MAGIC" -> s"0x${Caps.magic.toString(16)}u", "CAPABILITY_WORDS" -> s"${Caps.wordCount}u",
      "ACTIVE_CONTEXTS" -> s"${Caps.activeContexts}u", "RECORD_MAGIC" -> s"0x${Record.magic.toString(16)}u",
      "RECORD_BYTES" -> s"${Record.bytes}u", "RECORD_WORDS" -> "16u", "OPCODE_HIGH_BIT" -> s"${Caps.opcodeHighBit}u",
      "RECORD_AVAILABLE" -> "1u", "RECORD_CONSERVATIVE" -> "2u", "RECORD_STATUS_SHIFT" -> "2u",
      "DATA_VALUE" -> "1u", "DATA_AVAILABLE" -> "2u", "EXACT" -> "1u", "CONSERVATIVE" -> "2u",
      "BOUNDED_RECORD" -> "4u", "CONTEXT_ROOT_COOKIE" -> "8u", "ORDERED_PUBLICATION" -> "16u") ++
      opcodes.map { case (n, v) => s"OP_$n" -> s"${v}u" } ++
      fields.map { case (n, w) => s"${n}_WORD" -> s"${w}u" }
    val header = "/* Generated by EmitNativeVisibilityQueryAbi. GQV1/GQO1, little-endian words. */\n" +
      "#ifndef OPENGPU_VISIBILITY_QUERY_ABI_H\n#define OPENGPU_VISIBILITY_QUERY_ABI_H\n#include <stdint.h>\n\n" +
      constants.map { case (n, v) => s"#define OPENGPU_QUERY_$n $v\n" }.mkString +
      "\nstruct opengpu_visibility_query_record {\n" +
      "    uint32_t magic, bytes, context, cookie, flags, value, root;\n    uint32_t reserved[9];\n};\n\n#endif\n"
    val json = "{\n  \"version\":1,\n" +
      s"  \"capability_base\":${Caps.base},\n  \"capability_magic\":\"0x${Caps.magic.toString(16)}\",\n" +
      s"  \"capability_words\":[${Caps.words.map(v => s"\"0x${v.toString(16)}\"").mkString(",")}],\n" +
      s"  \"record_magic\":\"0x${Record.magic.toString(16)}\",\n  \"record_bytes\":${Record.bytes},\n" +
      "  \"record_alignment\":64,\n  \"allocation_limit_bits\":33,\n" +
      s"  \"active_contexts\":${Caps.activeContexts},\n  \"opcode_high_bit\":${Caps.opcodeHighBit},\n" +
      s"  \"opcodes\":{${opcodes.map { case (n, v) => s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$v" }.mkString(",")}},\n" +
      s"  \"record_words\":{${fields.map { case (n, v) => s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$v" }.mkString(",")}},\n" +
      "  \"command_fields\":{\"address\":\"SOURCE\",\"limit_low\":\"DESTINATION\",\"limit_high\":\"PATTERN[0]\",\"conservative\":\"PATTERN[1]\",\"context\":\"WIDTH\",\"cookie\":\"HEIGHT\",\"bytes\":64},\n" +
      "  \"data_bits\":{\"value\":0,\"available\":1},\n  \"record_flag_bits\":{\"available\":0,\"conservative\":1,\"status\":2},\n" +
      "  \"record_status_bits\":3,\n  \"reserved_flag_mask\":\"0xffffffe0\"\n}\n"
    for ((name, text) <- Seq("driver/opengpu_visibility_query_abi.h" -> header,
      "docs/abi/native-visibility-query-v1.json" -> json)) {
      val path = Paths.get(name)
      if (checking) require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == text, s"query ABI differs: $path")
      else { Files.createDirectories(path.getParent); Files.writeString(path, text, UTF_8) }
    }
    println(s"NATIVE_VISIBILITY_QUERY_ABI checked=$checking recordBytes=${Record.bytes} contexts=${Caps.activeContexts} opcodeHighBit=${Caps.opcodeHighBit}")
  }
}

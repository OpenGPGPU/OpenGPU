package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.util.Locale
import opengpu.graphics._
import opengpu.system._

/** One exact extension catalog plus references to the frozen complete domain
  * schemas. This does not publish a host discovery feature or protected UAPI.
  */
object EmitTessellationUniformSequenceAbi {
  def main(args:Array[String]):Unit={
    val check=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitTessellationUniformSequenceAbi [header] [schema] [--check]")
    var entries=Seq.empty[(String,Int,Int)]
    class Describe extends RawModule {
      val iso=Wire(new TessellationPatchSequenceDescriptor(opengpu.config.GpuConfig(),VertexShaderStageConfig(),12))
      val tri=Wire(new TessellationTrianglePatchSequenceDescriptor(opengpu.config.GpuConfig(),VertexShaderStageConfig(),12))
      val quad=Wire(new TessellationQuadPatchSequenceDescriptor(opengpu.config.GpuConfig(),VertexShaderStageConfig(),12))
      iso:=0.U.asTypeOf(iso);tri:=0.U.asTypeOf(tri);quad:=0.U.asTypeOf(quad)
      val all=Seq(TessellationNativeSequenceLayout.fields(iso,true).map(f=>(f.name,f.word,f.width)),
        TessellationNativeTriangleSequenceLayout.fields(tri,true).map(f=>(f.name,f.word,f.width)),
        TessellationNativeQuadSequenceLayout.fields(quad,true).map(f=>(f.name,f.word,f.width)))
      val extensions=all.map(_.filter(f=>TessellationUniformSequenceLayout.isUniformField(f._1)))
      require(extensions.forall(_==extensions.head))
      entries=extensions.head.map{case(n,w,b)=>(n.stripPrefix("template.source.viewport.system.uniforms."),w,b)}
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val records=Seq(("isoline",4,"native-tessellation-sequence-v1.json"),
      ("triangle",5,"native-tessellation-triangle-sequence-v2.json"),
      ("quad",6,"native-tessellation-quad-sequence-v3.json"))
    val prefix="OPENGPU_TESSELLATION_UNIFORM_SEQUENCE_"
    val header=new StringBuilder("/* Generated by EmitTessellationUniformSequenceAbi. Append-only GNT4/5/6 contract. */\n"+
      "#ifndef OPENGPU_TESSELLATION_UNIFORM_SEQUENCE_ABI_H\n#define OPENGPU_TESSELLATION_UNIFORM_SEQUENCE_ABI_H\n\n")
    header.append(s"#define ${prefix}WORDS 512u\n#define ${prefix}BYTES 2048u\n#define ${prefix}FIRST_WORD 496u\n")
    for((name,v,_)<-records){val n=name.toUpperCase(Locale.ROOT)
      header.append(s"#define $prefix${n}_MAGIC 0x474e540${v}u\n#define $prefix${n}_VERSION ${v}u\n")}
    for((name,w,b)<-entries){val n=name.replace('.','_').toUpperCase(Locale.ROOT)
      header.append(s"#define $prefix${n}_WORD ${w}u\n#define $prefix${n}_BITS ${b}u\n")}
    header.append("\n#endif\n")
    val rs=records.map{case(n,v,b)=>s"    {\"domain\":\"$n\",\"magic\":\"0x474e540$v\",\"version\":$v,\"baseSchema\":\"$b\"}"}.mkString(",\n")
    val fs=entries.map{case(n,w,b)=>s"    {\"name\":\"template.source.viewport.system.uniforms.$n\",\"word\":$w,\"bits\":$b,\"signed\":false}"}.mkString(",\n")
    val json=s"{\n  \"schema\":\"opengpu-tessellation-uniform-sequence-v1\",\n  \"words\":512,\"bytes\":2048,\"extensionFirstWord\":496,\n  \"records\":[\n$rs\n  ],\n  \"fields\":[\n$fs\n  ]\n}\n"
    EmitCommandAbi.writeOrCheck(check,Seq(paths.headOption.getOrElse("driver/opengpu_tessellation_uniform_sequence_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/tessellation-uniform-sequence.json")->json))
  }
}

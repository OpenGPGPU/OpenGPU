package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import opengpu.core.memory.StorageDescriptorLayout

object EmitStorageDescriptorAbi {
  def main(args: Array[String]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"))
    val d = StorageDescriptorLayout
    val header = "/* Generated by EmitStorageDescriptorAbi. GSB1 storage record. */\n" +
      "#ifndef OPENGPU_STORAGE_DESCRIPTOR_ABI_H\n#define OPENGPU_STORAGE_DESCRIPTOR_ABI_H\n" +
      s"#define OPENGPU_STORAGE_DESCRIPTOR_MAGIC 0x${d.magic.toString(16)}u\n" +
      s"#define OPENGPU_STORAGE_DESCRIPTOR_WORDS ${d.words}u\n" +
      d.fieldWords.map { case (name, word) =>
        s"#define OPENGPU_STORAGE_DESCRIPTOR_${name}_WORD ${word}u\n"
      }.mkString + "#endif\n"
    val path = Paths.get("driver/opengpu_storage_descriptor_abi.h")
    if (args.nonEmpty) require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == header)
    else Files.writeString(path, header, UTF_8)
  }
}

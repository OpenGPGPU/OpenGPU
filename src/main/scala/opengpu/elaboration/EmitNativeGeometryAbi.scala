package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.util.Locale
import opengpu.graphics._

object EmitNativeGeometryAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitNativeGeometryAbi [header-path] [json-path] [--check]")
    var programFields=Seq.empty[(String,Int,Int)];var drawFields=Seq.empty[(String,Int,Int)]
    class Describe extends RawModule {
      val program=Wire(new NativeGeometryProgram);program:=0.U.asTypeOf(program)
      val draw=Wire(new NativeGeometryDrawRecord);draw:=0.U.asTypeOf(draw)
      val pf=NativeGeometryProgramLayout.fields(program);val df=NativeGeometryDrawLayout.fields(draw)
      NativeTypedGraphicsLayout.check(program,pf,NativeGeometryProgramLayout.words)
      NativeTypedGraphicsLayout.check(draw,df,NativeGeometryDrawLayout.words)
      programFields=pf.map(f=>(f.name,f.word,f.width))
      drawFields=NativeGeometryResources.fields(draw.geometry).map(f=>(f.name,f.word,f.width))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_NATIVE_GEOMETRY_"
    val header=new StringBuilder("/* Generated by EmitNativeGeometryAbi. Explicit little-endian words.\n * Separate opt-in GND2/GNG1 contract; GND1 reserved words stay zero. */\n"+
      "#ifndef OPENGPU_NATIVE_GEOMETRY_ABI_H\n#define OPENGPU_NATIVE_GEOMETRY_ABI_H\n#ifdef __KERNEL__\ntypedef unsigned int opengpu_native_geometry_word;\n#else\n#include <stdint.h>\ntypedef uint32_t opengpu_native_geometry_word;\n#endif\n\n")
    header.append(s"#define ${prefix}PROGRAM_MAGIC 0x${NativeGeometryProgramLayout.magic.toString(16)}u\n#define ${prefix}PROGRAM_VERSION 1u\n#define ${prefix}PROGRAM_WORDS 256u\n#define ${prefix}PROGRAM_BYTES 1024u\n")
    header.append(s"#define ${prefix}DRAW_MAGIC 0x${NativeGeometryDrawLayout.magic.toString(16)}u\n#define ${prefix}DRAW_VERSION 2u\n#define ${prefix}DRAW_WORDS 512u\n#define ${prefix}DRAW_BYTES 2048u\n")
    for((name,value)<-Seq("RESOURCE_VERSION"->1,"SCALAR_PROGRAM_VERSION"->1,"MAX_INPUT_VERTICES"->6,
      "MAX_INVOCATIONS"->32,"MAX_OUTPUT_VERTICES"->256,"MAX_TOTAL_COMPONENTS"->1024,"MAX_COMPONENTS"->64,
      "MAX_VARYING_SLOTS"->16,"MAX_CODE_WORDS"->512))header.append(s"#define $prefix$name ${value}u\n")
    for((kind,fields)<-Seq("PROGRAM"->programFields,"DRAW"->drawFields);(name,word,bits)<-fields){
      val key=name.replace("[","").replace("]","").replace('.','_').toUpperCase(Locale.ROOT)
      header.append(s"#define $prefix${kind}_${key}_WORD ${word}u\n#define $prefix${kind}_${key}_BITS ${bits}u\n")
    }
    header.append("struct opengpu_native_geometry_program { opengpu_native_geometry_word words[256]; };\n")
    val masks=Array.fill[BigInt](256)(0)
    for(i<-0 until 3)masks(i)=(BigInt(1)<<32)-1
    for((_,word,bits)<-programFields;j<-0 until ((bits+31)/32))masks(word+j)=(BigInt(1)<<math.min(32,bits-j*32))-1
    header.append("static inline opengpu_native_geometry_word opengpu_native_geometry_word_at(const void *raw, unsigned int word) {\n"+
      "  const unsigned char *p=(const unsigned char *)raw+4u*word;\n"+
      "  return (opengpu_native_geometry_word)p[0]|(opengpu_native_geometry_word)p[1]<<8|(opengpu_native_geometry_word)p[2]<<16|(opengpu_native_geometry_word)p[3]<<24;\n}\n")
    header.append("static inline int opengpu_native_geometry_program_encoding_valid(const void *raw) {\n"+
      "  static const opengpu_native_geometry_word masks[256]={"+masks.map(m=>s"0x${m.toString(16)}u").mkString(",")+"};\n"+
      "  unsigned int i;\n  if(!raw || opengpu_native_geometry_word_at(raw,0)!=OPENGPU_NATIVE_GEOMETRY_PROGRAM_MAGIC ||\n"+
      "    opengpu_native_geometry_word_at(raw,1)!=1024u || opengpu_native_geometry_word_at(raw,2)!=1u)return 0;\n"+
      "  for(i=0;i<256u;i++)if(opengpu_native_geometry_word_at(raw,i)&~masks[i])return 0;\n  return 1;\n}\n#endif\n")
    def fieldsJson(fields: Seq[(String,Int,Int)]): String=fields.map{case(n,w,b)=>
      s"{\"name\":\"$n\",\"word\":$w,\"bits\":$b,\"signed\":false}"}.mkString(",")
    val json=s"""{
  "program":{"magic":"0x474e4701","version":1,"words":256,"bytes":1024,"fields":[${fieldsJson(programFields)}]},
  "drawExtension":{"base":"native-binned-graphics-v1.json","magic":"0x474e4402","version":2,"words":512,"bytes":2048,"fields":[${fieldsJson(drawFields)}]},
  "limits":{"inputVertices":6,"invocations":32,"outputVertices":256,"totalComponents":1024,"components":64,"varyingSlots":16,"codeWords":512},
  "requiresExplicitGeometryProvider":true
}
"""
    EmitCommandAbi.writeOrCheck(checking,Seq(paths.headOption.getOrElse("driver/opengpu_native_geometry_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/native-geometry-v1.json")->json))
    println(s"NATIVE_GEOMETRY_ABI programFields=${programFields.size} drawExtensionFields=${drawFields.size} checked=$checking")
  }
}

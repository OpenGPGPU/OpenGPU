package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import opengpu.config.{ComputeResourceProfile,GpuConfig}
import opengpu.system.ComputeResourceCapabilities

object EmitComputeResourceAbi {
  def main(args: Array[String]): Unit={
    require(args.isEmpty || args.toSeq==Seq("--check"))
    val c=ComputeResourceCapabilities
    val header="/* Generated by EmitComputeResourceAbi. GCR1 reports actual compute resources. */\n"+
      "#ifndef OPENGPU_COMPUTE_RESOURCE_ABI_H\n#define OPENGPU_COMPUTE_RESOURCE_ABI_H\n"+
      s"#define OPENGPU_COMPUTE_RESOURCE_CAPABILITIES 0x${c.base.toHexString}u\n"+
      s"#define OPENGPU_COMPUTE_RESOURCE_MAGIC 0x${c.magic.toString(16)}u\n"+
      s"#define OPENGPU_COMPUTE_RESOURCE_WORDS ${c.wordCount}u\n"+
      c.fields.zipWithIndex.map{case(n,i)=>s"#define OPENGPU_COMPUTE_RESOURCE_REG_$n 0x${(c.base+4*i).toHexString}u\n"}.mkString+
      "#define OPENGPU_COMPUTE_RESOURCE_CHECKED_LOCAL_PRODUCT (1u << 0)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_UINT32_GRID_AXES (1u << 1)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_ONE_GROUP_PER_CU (1u << 2)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_WORD_ATOMICS (1u << 3)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_IMAGE_COMMANDS (1u << 4)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_STORAGE_COMMANDS (1u << 5)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_UNIFORM_COMMANDS (1u << 6)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_TEXTURE_COMMANDS (1u << 7)\n"+
      "#define OPENGPU_COMPUTE_RESOURCE_ATOMIC_COUNTER_COMMANDS (1u << 8)\n#endif\n"
    val defaults=c.words(ComputeResourceProfile(GpuConfig(),1,8))
    val mobile=c.words(ComputeResourceProfile(GpuConfig(),4,32))
    val json=s"""{
  "schema":"compute-resource-v1",
  "base":${c.base},
  "word_count":${c.wordCount},
  "magic":${c.magic},
  "fields":[${c.fields.zipWithIndex.map{case(n,i)=>s"{\"name\":\"${n.toLowerCase(java.util.Locale.ROOT)}\",\"word\":$i,\"address\":${c.base+4*i}}"}.mkString(",")}],
  "constructor_default_words":[${defaults.mkString(",")}],
  "mobile_candidate_words":[${mobile.mkString(",")}],
  "ownership":"actual compute GpuConfig, CU count and memory AXI width; independent of legacy graphics configuration",
  "local_axis":"minimum of physical per-CU lane*warp capacity and the uint16 launch-axis encoding limit",
  "simt":"physical entry capacity of the existing controller; does not imply instruction-driven vector-branch execution",
  "scope":"read-only hardware quantities; not an API capability or full resource/visibility contract"
}
"""
    for((name,text)<-Seq("driver/opengpu_compute_resource_abi.h"->header,"docs/abi/compute-resource-v1.json"->json)){
      val path=Paths.get(name)
      if(args.nonEmpty)require(Files.isRegularFile(path)&&Files.readString(path,UTF_8)==text,s"compute resource ABI differs: $name")
      else{Files.createDirectories(path.getParent);Files.writeString(path,text,UTF_8)}
    }
    println(s"COMPUTE_RESOURCE_ABI checked=${args.nonEmpty} words=${c.wordCount} base=${c.base}")
  }
}

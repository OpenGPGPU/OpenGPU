package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.util.Locale
import opengpu.graphics._

/** Geometry's separately versioned uniform records. This emits a transport
  * schema; it never enables GUC1, native draw or API capability bits.
  */
object EmitGeometryUniformAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitGeometryUniformAbi [header-path] [json-path] [--check]")
    var schemas=Seq.empty[(String,BigInt,Seq[(String,Int,Int)])]
    class Describe extends RawModule {
      val root=Wire(new ShaderUniformRootRecord(2));root:=0.U.asTypeOf(root)
      val binding=Wire(new ShaderUniformBindingRecord(4));binding:=0.U.asTypeOf(binding)
      def describe(name: String,d: Data,magic: BigInt,fields: Seq[NativeTypedGraphicsLayout.Field]): Unit={
        NativeTypedGraphicsLayout.check(d,fields,16)
        schemas=schemas:+((name,magic,fields.map(f=>(f.name,f.word,f.width))))
      }
      describe("root",root,GeometryUniformResources.rootMagic,ShaderUniformRootLayout.fields(root))
      describe("binding",binding,GeometryUniformResources.bindingMagic,ShaderUniformBindingLayout.fields(binding))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_GEOMETRY_UNIFORM_"
    val header=new StringBuilder("/* Generated by EmitGeometryUniformAbi. Little-endian words.\n * All reserved words and narrow-field padding must be zero. */\n"+
      "#ifndef OPENGPU_GEOMETRY_UNIFORM_ABI_H\n#define OPENGPU_GEOMETRY_UNIFORM_ABI_H\n#ifdef __KERNEL__\n#include <linux/types.h>\ntypedef u32 opengpu_geometry_uniform_word;\n#else\n#include <stdint.h>\ntypedef uint32_t opengpu_geometry_uniform_word;\n#endif\n\n")
    for((name,value)<-Seq("VERSION"->GeometryUniformResources.version,"STAGE"->GeometryUniformResources.stage,
      "STAGE_MASK"->GeometryUniformResources.stageMask,"BLOCKS_PER_STAGE"->ShaderUniformLimits.blocksPerStage,
      "BINDINGS"->ShaderUniformLimits.bindings,"BLOCK_BYTES"->ShaderUniformLimits.blockBytes,
      "OFFSET_ALIGNMENT"->ShaderUniformLimits.offsetAlignment,"DEFAULT_COMPONENTS"->ShaderUniformLimits.defaultComponents(3),
      "DEFAULT_BLOCK"->ShaderUniformLimits.defaultBlock,"TABLE_ALIGNMENT"->64,"DEFAULT_ALIGNMENT"->4))
      header.append(s"#define $prefix$name ${value}u\n")
    for((name,magic,fields)<-schemas){
      val p=prefix+name.toUpperCase(Locale.ROOT)+"_"
      header.append(s"#define ${p}MAGIC 0x${magic.toString(16)}u\n#define ${p}WORDS 16u\n#define ${p}BYTES 64u\n")
      for((field,word,bits)<-fields){val n=field.replace('.','_').toUpperCase(Locale.ROOT)
        header.append(s"#define $p${n}_WORD ${word}u\n#define $p${n}_BITS ${bits}u\n")}
      header.append(s"struct opengpu_geometry_uniform_$name { opengpu_geometry_uniform_word words[16]; };\n\n")
    }
    header.append("#endif\n")
    val layouts=schemas.map{case(name,magic,fields)=>
      val entries=fields.map{case(n,w,b)=>s"{\"name\":\"$n\",\"word\":$w,\"bits\":$b,\"signed\":false}"}.mkString(",")
      s"    {\"name\":\"$name\",\"magic\":\"0x${magic.toString(16)}\",\"words\":16,\"bytes\":64,\"fields\":[$entries]}"
    }.mkString(",\n")
    val json=s"{\n  \"version\":2,\"stage\":3,\"stageMask\":8,\"blocksPerStage\":12,\"bindings\":24,\"blockBytes\":16384,\"offsetAlignment\":256,\"defaultComponents\":1024,\n  \"layouts\":[\n$layouts\n  ]\n}\n"
    EmitCommandAbi.writeOrCheck(checking,Seq(
      paths.headOption.getOrElse("driver/opengpu_geometry_uniform_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/geometry-uniform-v2.json")->json))
    println(s"GEOMETRY_UNIFORM_ABI layouts=${schemas.size} checked=$checking")
  }
}

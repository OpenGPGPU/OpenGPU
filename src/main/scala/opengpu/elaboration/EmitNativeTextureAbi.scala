package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import java.util.Locale
import opengpu.graphics._

object EmitNativeTextureAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitNativeTextureAbi [header-path] [json-path] [--check]")
    var schemas=Seq.empty[(String,Int,BigInt,Seq[(String,Int,Int)])]
    class Describe extends RawModule {
      val root=Wire(new ShaderTextureRootRecord);root:=0.U.asTypeOf(root)
      val binding=Wire(new ShaderTextureBindingRecord);binding:=0.U.asTypeOf(binding)
      val packet=Wire(new ShaderTextureCoordinateRecord);packet:=0.U.asTypeOf(packet)
      def describe(name: String,d: Data,words: Int,magic: BigInt,fs: Seq[NativeTypedGraphicsLayout.Field]): Unit={
        NativeTypedGraphicsLayout.check(d,fs,words);schemas=schemas:+((name,words,magic,fs.map(f=>(f.name,f.word,f.width))))
      }
      describe("root",root,32,ShaderTextureRootLayout.magic,ShaderTextureRootLayout.fields(root))
      describe("binding",binding,16,ShaderTextureBindingLayout.magic,ShaderTextureBindingLayout.fields(binding))
      describe("packet",packet,16,ShaderTextureCoordinateLayout.magic,ShaderTextureCoordinateLayout.fields(packet))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val header=new StringBuilder("/* Generated by EmitNativeTextureAbi. Little-endian32-bit words.\n * Narrow fields have zero padding; all reserved words are zero. */\n"+
      "#ifndef OPENGPU_NATIVE_TEXTURE_ABI_H\n#define OPENGPU_NATIVE_TEXTURE_ABI_H\n#include <stdint.h>\n\n")
    val prefix="OPENGPU_NATIVE_TEXTURE_"
    for((n,v)<-Seq("VERSION"->"1u","REFERENCE_DISABLED"->"0u","REFERENCE_ENABLED"->"1u","MAX_BINDINGS_PER_STAGE"->"32u",
      "STAGE_VERTEX"->"0u","STAGE_FRAGMENT"->"1u","TABLE_ALIGNMENT"->"64u",
      "SCALAR_FETCH_BASE"->"0x0400000bu","VECTOR_FETCH_BASE"->"0x0800002bu","VECTOR_FETCH_UNMASKED_BASE"->"0x0a00002bu",
      "FETCH_COMPONENT_SHIFT"->"12u","FETCH_COMPONENT_MASK"->"0x3000u"))header.append(s"#define $prefix$n $v\n")
    for((name,words,magic,fs)<-schemas){val p=prefix+name.toUpperCase(Locale.ROOT)+"_"
      header.append(s"#define ${p}MAGIC 0x${magic.toString(16)}u\n#define ${p}WORDS ${words}u\n#define ${p}BYTES ${words*4}u\n")
      for((field,word,bits)<-fs){val n=field.replace('.','_').toUpperCase(Locale.ROOT)
        header.append(s"#define $p${n}_WORD ${word}u\n#define $p${n}_BITS ${bits}u\n")}
      header.append(s"struct opengpu_native_texture_$name { uint32_t words[${p}WORDS]; };\n\n")
    }
    header.append("#endif\n")
    val bodies=schemas.map{case(name,words,magic,fs)=>
      val fields=fs.map{case(n,w,b)=>s"{\"name\":\"$n\",\"word\":$w,\"bits\":$b,\"signed\":false}"}.mkString(",")
      s"    {\"name\":\"$name\",\"magic\":\"0x${magic.toString(16)}\",\"words\":$words,\"bytes\":${words*4},\"fields\":[$fields]}"
    }.mkString(",\n")
    val json=s"{\n  \"version\":1,\"tableAlignment\":64,\"maxBindingsPerStage\":32,\n  \"layouts\":[\n$bodies\n  ]\n}\n"
    for((name,body)<-Seq(paths.headOption.getOrElse("driver/opengpu_native_texture_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/native-texture-v1.json")->json)){
      val p=Paths.get(name)
      if(checking)require(Files.isRegularFile(p) && Files.readString(p,UTF_8)==body,s"native texture ABI differs: $p")
      else{Option(p.getParent).foreach(x=>Files.createDirectories(x));Files.writeString(p,body,UTF_8)}
    }
    println(s"NATIVE_TEXTURE_ABI layouts=${schemas.size} checked=$checking")
  }
}

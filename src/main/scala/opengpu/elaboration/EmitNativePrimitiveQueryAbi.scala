package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import opengpu.graphics.{NativePrimitiveQueryCapabilities=>Caps,PrimitiveQueryRecord=>Record}

object EmitNativePrimitiveQueryAbi {
  def main(args: Array[String]): Unit={
    require(args.isEmpty || args.toSeq==Seq("--check"),"EmitNativePrimitiveQueryAbi [--check]")
    val checking=args.nonEmpty
    val fields=Seq("MAGIC"->0,"BYTES"->1,"CONTEXT"->2,"COOKIE"->3,"FLAGS"->4,
      "COUNT_LO"->5,"COUNT_HI"->6,"ROOT"->7,"TARGET"->8,"RESERVED"->9)
    val actions=Seq("BEGIN"->0,"END"->1,"POLL"->2,"RESULT"->3)
    val features=Seq("SATURATING64","CLAMPING32","FULL_ROOT_NAMESPACES","GPU_COMPLETED_RECORDS",
      "ACKNOWLEDGED_PRIMITIVES","RESET_DRAIN")
    val constants=Seq("CAPABILITIES"->s"0x${Caps.base.toHexString}u",
      "CAPABILITY_MAGIC"->s"0x${Caps.magic.toString(16)}u","CAPABILITY_WORDS"->s"${Caps.wordCount}u",
      "OPCODE"->s"${Caps.opcode}u","OPCODE_HIGH_BIT"->s"${Caps.opcodeHighBit}u",
      "RECORD_MAGIC"->s"0x${Record.magic.toString(16)}u","RECORD_BYTES"->s"${Record.bytes}u",
      "RECORD_ALIGNMENT"->"64u","ACTIVE_CONTEXTS"->s"${Caps.activeContexts}u",
      "COUNT_BITS"->s"${Caps.countBits}u","API_BITS"->s"${Caps.apiBits}u",
      "TARGET"->s"0x${Record.target.toHexString}u","PATTERN_LIMIT_HIGH"->"1u",
      "PATTERN_ACTION_SHIFT"->"1u","PATTERN_ALLOWED"->"7u",
      "RECORD_AVAILABLE"->"1u","RECORD_FAULT_SHIFT"->"2u","RECORD_FLAGS_ALLOWED"->"0x1du",
      "COMPLETION_AVAILABLE"->"1u","COMPLETION_VALUE_WORD"->"0u","COMPLETION_FLAGS_WORD"->"1u") ++
      actions.map{case(n,v)=>s"ACTION_$n"->s"${v}u"} ++
      fields.map{case(n,v)=>s"${n}_WORD"->s"${v}u"} ++
      features.zipWithIndex.map{case(n,i)=>s"FEATURE_$n"->s"(1u << $i)"}
    val header="/* Generated by EmitNativePrimitiveQueryAbi. GQP1/GPO1, little-endian words. */\n"+
      "#ifndef OPENGPU_PRIMITIVE_QUERY_ABI_H\n#define OPENGPU_PRIMITIVE_QUERY_ABI_H\n#include <stdint.h>\n#include <stddef.h>\n\n"+
      constants.map{case(n,v)=>s"#define OPENGPU_PQ_$n $v\n"}.mkString+
      "\nstruct opengpu_primitive_query_record {\n"+
      "    uint32_t magic, bytes, context, cookie, flags, count_lo, count_hi, root, target;\n"+
      "    uint32_t reserved[7];\n};\n"+
      "/* Opcode13: SOURCE=record VA, DESTINATION=limit low, PATTERN[0]=limit high,\n"+
      " * PATTERN[2:1]=action, BYTES=64, WIDTH=context, HEIGHT=cookie, FLAGS=0.\n"+
      " * SOURCE_STRIDE is ignored. Drain begin/end replies before subsequent draws.\n"+
      " * A failed publication/reset invalidates the record lease; use a fresh cookie.\n"+
      " * DATA_LO is clamped uint32 result; DATA_HI bit0 is availability. */\n"+
      "#if defined(__cplusplus)\n#define OPENGPU_PQ_ASSERT static_assert\n#else\n#define OPENGPU_PQ_ASSERT _Static_assert\n#endif\n"+
      s"OPENGPU_PQ_ASSERT(sizeof(struct opengpu_primitive_query_record)==${Record.bytes}, \"GPO1 size\");\n"+
      fields.map{case(n,i)=>s"OPENGPU_PQ_ASSERT(offsetof(struct opengpu_primitive_query_record,${n.toLowerCase(java.util.Locale.ROOT)})==${i*4}, \"GPO1 $n\");\n"}.mkString+
      "#undef OPENGPU_PQ_ASSERT\n#endif\n"
    val json=s"""{
  "schema":"native-primitive-query-v1",
  "capability_base":${Caps.base},
  "capability_words":[${Caps.words.mkString(",")}],
  "record_bytes":${Record.bytes},
  "record_alignment":64,
  "record_words":{${fields.map{case(n,v)=>s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$v"}.mkString(",")}},
  "actions":{${actions.map{case(n,v)=>s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$v"}.mkString(",")}},
  "feature_bits":{${features.zipWithIndex.map{case(n,i)=>s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$i"}.mkString(",")}},
  "command":{"opcode":${Caps.opcode},"address":"SOURCE","limit_low":"DESTINATION","limit_high":"PATTERN[0]","action":"PATTERN[2:1]","bytes":64,"context":"WIDTH","cookie":"HEIGHT","source_stride":"ignored","flags":0,"pattern_reserved_zero":"31:3"},
  "completion":{"opcode_high_bit":16,"value":"DATA_LO clamped uint32","available":"DATA_HI[0]","data_hi_reserved_zero":"31:1"},
  "record_flags":{"available":0,"fault":"4:2","reserved_zero":"31:5,1"},
  "statuses":{"success":0,"bounds_or_encoding":1,"record_identity":2,"memory_or_render_fault":3,"cancelled":4,"active_or_missing_lease":5,"capacity":6},
  "input_reserved_zero_words":[9,10,11,12,13,14,15],
  "render_context":"opcode7 WIDTH and captured full root",
  "events":"one successful source primitive after all feedback stores acknowledge, before clipping and tile fanout",
  "reset":"drain owned offers/replies and renderer, clear active rows, require fresh cookies",
  "scope":"hardware ABI; API object names and CPU coherence are caller contracts"
}
"""
    for((name,text)<-Seq("driver/opengpu_primitive_query_abi.h"->header,"docs/abi/native-primitive-query-v1.json"->json)){
      val path=Paths.get(name)
      if(checking)require(Files.isRegularFile(path) && Files.readString(path,UTF_8)==text,s"primitive-query ABI differs: $path")
      else{Files.createDirectories(path.getParent);Files.writeString(path,text,UTF_8)}
    }
    println(s"NATIVE_PRIMITIVE_QUERY_ABI checked=$checking recordBytes=${Record.bytes} contexts=${Caps.activeContexts} opcode=${Caps.opcode}")
  }
}

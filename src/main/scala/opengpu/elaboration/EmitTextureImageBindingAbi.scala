package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import java.util.Locale
import opengpu.graphics._

object EmitTextureImageBindingAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitTextureImageBindingAbi [header-path] [json-path] [--check]")
    var fields=Seq.empty[(String,Int,Int)]
    class Describe extends RawModule {
      val d=Wire(new TextureImageBindingRecord);d:=0.U.asTypeOf(d)
      val fs=TextureImageBindingLayout.fields(d);NativeTypedGraphicsLayout.check(d,fs,TextureImageBindingLayout.words)
      fields=fs.map(f=>(f.name,f.word,f.width))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_TEXTURE_IMAGE_BINDING_"
    val header=new StringBuilder("/* Generated by EmitTextureImageBindingAbi. Little-endian32-bit words.\n"+
      " * Each narrow field has zero padding. Reserved words are zero.\n"+
      " * This is a image format/level-table record, not a native feature advertisement. */\n"+
      "#ifndef OPENGPU_TEXTURE_IMAGE_BINDING_ABI_H\n#define OPENGPU_TEXTURE_IMAGE_BINDING_ABI_H\n#include <stdint.h>\n\n")
    for((name,value)<-Seq("MAGIC"->"0x47584901u","VERSION"->"1u","WORDS"->"32u","BYTES"->"128u","TABLE_ALIGNMENT"->"64u",
      "HEADER_MAGIC_WORD"->"0u","HEADER_BYTES_WORD"->"1u","HEADER_VERSION_WORD"->"2u",
      "TARGET_2D"->"0u","TARGET_2D_ARRAY"->"1u","TARGET_CUBE"->"2u","TARGET_3D"->"3u",
      "SWIZZLE_LEGACY"->"0u","SWIZZLE_EXPLICIT"->"1u","SWIZZLE_RED"->"0u","SWIZZLE_GREEN"->"1u",
      "SWIZZLE_BLUE"->"2u","SWIZZLE_ALPHA"->"3u","SWIZZLE_ZERO"->"4u","SWIZZLE_ONE"->"5u",
      "STATUS_OK"->"0u","STATUS_VIEW"->"1u","STATUS_BOUNDS"->"2u","STATUS_MEMORY"->"3u",
      "STATUS_CANCELLED"->"4u","STATUS_COORDINATE"->"5u","STATUS_FORMAT"->"6u","STATUS_ENCODING"->"7u",
      "FAULT_NONE"->"0u","FAULT_IMAGE"->"1u","FAULT_LEVEL"->"2u","FAULT_DATA"->"3u","FAULT_LAYOUT"->"4u","FAULT_COORDINATE"->"5u"))header.append(s"#define $prefix$name $value\n")
    for((name,word,bits)<-fields){val upper=name.replace('.','_').toUpperCase(Locale.ROOT)
      require(upper.matches("[A-Z0-9_]+"));header.append(s"#define $prefix${upper}_WORD ${word}u\n#define $prefix${upper}_BITS ${bits}u\n")}
    header.append("struct opengpu_texture_image_binding { uint32_t words[OPENGPU_TEXTURE_IMAGE_BINDING_WORDS]; };\n\n#endif\n")
    val body=fields.map{case(name,word,bits)=>s"    {\"name\":\"$name\",\"word\":$word,\"bits\":$bits,\"signed\":false}"}.mkString(",\n")
    val json=s"{\n  \"magic\":\"0x47584901\",\"version\":1,\"words\":32,\"bytes\":128,\"tableAlignment\":64,\n  \"fields\":[\n$body\n  ]\n}\n"
    for((name,contents)<-Seq(paths.headOption.getOrElse("driver/opengpu_texture_image_binding_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/texture-image-binding-v1.json")->json)){
      val path=Paths.get(name)
      if(checking)require(Files.isRegularFile(path) && Files.readString(path,UTF_8)==contents,s"texture level ABI differs: $path")
      else{Option(path.getParent).foreach(p=>Files.createDirectories(p));Files.writeString(path,contents,UTF_8)}
    }
    println(s"TEXTURE_IMAGE_BINDING_ABI version=1 bytes=128 fields=${fields.size} checked=$checking")
  }
}

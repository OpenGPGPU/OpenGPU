package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import opengpu.system.{NativeShaderExecutionCapabilities => Caps}
import opengpu.core.trap.TrapCause

object EmitNativeShaderExecutionAbi {
  def main(args: Array[String]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"), "EmitNativeShaderExecutionAbi [--check]")
    val constants: Seq[(String, BigInt)] = Seq("CAPABILITIES" -> Caps.base,
      "CAPABILITY_MAGIC" -> Caps.magic, "CAPABILITY_WORDS" -> Caps.wordCount,
      "INSTRUCTION_QUOTA" -> Caps.quotaRegister, "DEFAULT_QUOTA" -> Caps.defaultQuota,
      "MIN_QUOTA" -> 1, "MAX_QUOTA" -> BigInt("ffffffff", 16),
      "LIMIT_TRAP_CAUSE" -> TrapCause.shaderInstructionLimit,
      "INTERRUPT_TRAP_CAUSE" -> TrapCause.shaderInterrupted,
      "SIMT_STACK_OVERFLOW_TRAP_CAUSE" -> TrapCause.simtStackOverflow,
      "SIMT_STACK_UNDERFLOW_TRAP_CAUSE" -> TrapCause.simtStackUnderflow)
    val features = Seq("PER_WARP_ADMITTED_FETCHES", "KERNEL_SNAPSHOT", "RESET_INTERRUPT",
      "ATTRIBUTED_TRAPS", "NONZERO_NATIVE_QUOTA")
    val header = "/* Generated by EmitNativeShaderExecutionAbi. GSL1 is not a cycle timeout. */\n" +
      "#ifndef OPENGPU_SHADER_EXECUTION_ABI_H\n#define OPENGPU_SHADER_EXECUTION_ABI_H\n\n" +
      constants.map { case (n, v) => s"#define OPENGPU_SHADER_$n 0x${v.toString(16)}u\n" }.mkString +
      features.zipWithIndex.map { case (n, i) => s"#define OPENGPU_SHADER_FEATURE_$n (1u << $i)\n" }.mkString +
      "\n/* Quota updates require a drained VM/command/render context. Zero is rejected,\n" +
      " * including partial byte writes that would produce zero. Reset interrupts\n" +
      " * graphics-owned CUs and drains actual replies; quota policy survives it. */\n#endif\n"
    val json = s"""{
  "schema":"native-shader-execution-v1",
  "capability_base":${Caps.base},
  "capability_words":[${Caps.words.mkString(",")}],
  "quota_register":${Caps.quotaRegister},
  "quota_bits":32,
  "default_quota":${Caps.defaultQuota},
  "minimum_quota":1,
  "maximum_quota":4294967295,
  "feature_bits":{${features.zipWithIndex.map { case (n, i) => s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$i" }.mkString(",")}},
  "trap_causes":{"instruction_limit":${TrapCause.shaderInstructionLimit},"interrupted":${TrapCause.shaderInterrupted},"simt_stack_overflow":${TrapCause.simtStackOverflow},"simt_stack_underflow":${TrapCause.simtStackUnderflow}},
  "quota_unit":"admitted instruction fetches per allocated warp, including branches and cease",
  "scope":"native typed and binned shared-CU graphics; compute compatibility uses quota zero",
  "snapshot":"kernel acceptance; later warp allocations retain the same limit",
  "writes":"32-bit little-endian byte strobes, drained context only, resulting zero rejected",
  "reset":"interrupt graphics-owned and irrevocably admitted graphics kernels; drain real replies; retain policy",
  "limitations":"no cycle deadline for memory, texture or unserviced execution ports; not full watchdog closure"
}
"""
    for ((name, text) <- Seq("driver/opengpu_shader_execution_abi.h" -> header,
        "docs/abi/native-shader-execution-v1.json" -> json)) {
      val path = Paths.get(name)
      if (args.nonEmpty) require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == text, s"shader execution ABI differs: $path")
      else { Files.createDirectories(path.getParent); Files.writeString(path, text, UTF_8) }
    }
    println(s"NATIVE_SHADER_EXECUTION_ABI checked=${args.nonEmpty} quotaBits=32 default=${Caps.defaultQuota}")
  }
}

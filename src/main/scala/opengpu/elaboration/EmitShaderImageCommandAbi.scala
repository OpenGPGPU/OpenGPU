package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import opengpu.graphics.{ShaderImageCommandMmioRegs, ShaderImageDescriptorLayout}

object EmitShaderImageCommandAbi {
  def main(args: Array[String]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"))
    val r = ShaderImageCommandMmioRegs
    require(r.controlMask == BigInt("ff01", 16))
    val fields = Seq("CONTROL", "TABLE_BASE", "TABLE_LIMIT_LO", "TABLE_LIMIT_HI",
      "CONTEXT", "PASS", "GENERATION", "MAGIC")
    val header = "/* Generated by EmitShaderImageCommandAbi. GIM1 command transport. */\n" +
      "#ifndef OPENGPU_SHADER_IMAGE_COMMAND_ABI_H\n#define OPENGPU_SHADER_IMAGE_COMMAND_ABI_H\n" +
      s"#define OPENGPU_IMAGE_COMMAND_BASE 0x${r.base.toHexString}u\n" +
      s"#define OPENGPU_IMAGE_COMMAND_END 0x${r.end.toHexString}u\n" +
      s"#define OPENGPU_IMAGE_COMMAND_MAGIC_VALUE 0x${r.magic.toString(16)}u\n" +
      s"#define OPENGPU_IMAGE_COMMAND_WORDS ${fields.size - 1}u\n" +
      s"#define OPENGPU_IMAGE_COMMAND_DESCRIPTOR_BYTES ${ShaderImageDescriptorLayout.bytes}u\n" +
      fields.zipWithIndex.map { case (name, i) =>
        s"#define OPENGPU_IMAGE_COMMAND_REG_$name 0x${(r.base + i * 4).toHexString}u\n"
      }.mkString + "#define OPENGPU_IMAGE_COMMAND_ENABLE 1u\n" +
      "#define OPENGPU_IMAGE_COMMAND_VERSION_SHIFT 8u\n#endif\n"
    val path = Paths.get("driver/opengpu_shader_image_command_abi.h")
    if(args.nonEmpty) require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == header)
    else Files.writeString(path, header, UTF_8)
    println(s"IMAGE_COMMAND_ABI checked=${args.nonEmpty} base=${r.base} words=${fields.size - 1}")
  }
}

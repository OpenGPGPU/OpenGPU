package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}

/** Shared generator/check for simple command MMIO ABI headers. */
object EmitCommandAbi {
  private def hex(v: Any): String = v match {
    case i: Int => java.lang.Integer.toHexString(i)
    case l: Long => java.lang.Long.toHexString(l)
    case b: BigInt => b.toString(16)
    case other => other.toString
  }

  def render(
    generator: String,
    comment: String,
    guard: String,
    prefix: String,
    base: Int,
    end: Int,
    magic: BigInt,
    fields: Seq[String],
    descriptorBytes: Option[Int] = None
  ): String = {
    val sb = new StringBuilder
    sb.append(s"/* Generated by $generator. $comment */\n")
    sb.append(s"#ifndef $guard\n#define $guard\n")
    sb.append(s"#define ${prefix}_BASE 0x${hex(base)}u\n")
    sb.append(s"#define ${prefix}_END 0x${hex(end)}u\n")
    sb.append(s"#define ${prefix}_MAGIC_VALUE 0x${hex(magic)}u\n")
    sb.append(s"#define ${prefix}_WORDS ${fields.size - 1}u\n")
    descriptorBytes.foreach(b => sb.append(s"#define ${prefix}_DESCRIPTOR_BYTES ${b}u\n"))
    fields.zipWithIndex.foreach { case (name, i) =>
      sb.append(s"#define ${prefix}_REG_$name 0x${hex(base + i * 4)}u\n")
    }
    sb.append(s"#define ${prefix}_ENABLE 1u\n")
    sb.append(s"#define ${prefix}_VERSION_SHIFT 8u\n")
    sb.append("#endif\n")
    sb.toString()
  }

  def emit(args: Array[String], defaultPath: String, header: String): Unit =
    emitFixed(args, Seq(defaultPath -> header))

  def emitFixed(args: Array[String], files: Seq[(String, String)]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"), "use no args to write or --check")
    val checking = args.nonEmpty
    files.foreach { case (name, content) =>
      val path = Paths.get(name)
      if (checking) {
        require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == content, s"ABI differs: $path")
      } else {
        Option(path.getParent).foreach(p => Files.createDirectories(p))
        Files.writeString(path, content, UTF_8)
      }
    }
  }
}

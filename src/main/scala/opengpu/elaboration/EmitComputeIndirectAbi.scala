package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import opengpu.command.ComputeIndirectCapabilities

object EmitComputeIndirectAbi {
  def main(args: Array[String]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"))
    val header = """/* Generated by EmitComputeIndirectAbi. Optional GCI1 hardware profile. */
#ifndef OPENGPU_INDIRECT_COMPUTE_ABI_H
#define OPENGPU_INDIRECT_COMPUTE_ABI_H
#define OPENGPU_INDIRECT_COMPUTE_CAPABILITIES 0x340u
#define OPENGPU_INDIRECT_COMPUTE_MAGIC 0x47434901u
#define OPENGPU_INDIRECT_COMPUTE_WORDS 8u
#define OPENGPU_INDIRECT_COMPUTE_OPCODE 14u
#define OPENGPU_INDIRECT_COMPUTE_ARGUMENT_BYTES 12u
#define OPENGPU_INDIRECT_COMPUTE_ALIGNMENT 4u
#define OPENGPU_INDIRECT_COMPUTE_MAX_GROUP_COUNT 0xffffffffu
#define OPENGPU_INDIRECT_COMPUTE_VIRTUAL_ARGUMENTS (1u << 0)
#define OPENGPU_INDIRECT_COMPUTE_BOUNDED_VIEW (1u << 1)
#define OPENGPU_INDIRECT_COMPUTE_ZERO_NOOP (1u << 2)
#define OPENGPU_INDIRECT_COMPUTE_EVENT_DEPENDENCY (1u << 3)
#define OPENGPU_INDIRECT_COMPUTE_DMA_DEPENDENCY (1u << 4)
#define OPENGPU_INDIRECT_COMPUTE_RESET_REPLY_DRAIN (1u << 5)
#define OPENGPU_INDIRECT_COMPUTE_CAPTURED_LAUNCH (1u << 6)
#endif
"""
    val path=Paths.get("driver/opengpu_indirect_compute_abi.h")
    if(args.nonEmpty)require(Files.isRegularFile(path) && Files.readString(path,UTF_8)==header,"indirect compute ABI differs")
    else Files.writeString(path,header,UTF_8)
    require(ComputeIndirectCapabilities.base==0x340 && ComputeIndirectCapabilities.opcode==14)
    println(s"COMPUTE_INDIRECT_ABI checked=${args.nonEmpty} argumentBytes=12 opcode=14")
  }
}

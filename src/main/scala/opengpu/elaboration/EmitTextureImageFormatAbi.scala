package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import opengpu.graphics.TypedColorFormat

/** Internal storage IDs shared with typed attachments, not GL enum values. */
object EmitTextureImageFormatAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitTextureImageFormatAbi [header-path] [json-path] [--check]")
    val header=new StringBuilder("/* Generated by EmitTextureImageFormatAbi. Internal typed storage IDs.\n"+
      " * Byte layouts match TypedColorFormat. No native sampling capability is advertised. */\n"+
      "#ifndef OPENGPU_TEXTURE_IMAGE_FORMAT_ABI_H\n#define OPENGPU_TEXTURE_IMAGE_FORMAT_ABI_H\n\n"+
      "#define OPENGPU_TEXTURE_FORMAT_VERSION 1u\n#define OPENGPU_TEXTURE_FORMAT_BITS 6u\n#define OPENGPU_TEXTURE_FORMAT_COUNT 36u\n"+
      "#define OPENGPU_TEXTURE_FETCH_STATUS_FORMAT 6u\n#define OPENGPU_TEXTURE_FETCH_FAULT_DESCRIPTOR 1u\n"+
      "#define OPENGPU_TEXTURE_FETCH_FAULT_DATA 2u\n#define OPENGPU_TEXTURE_FETCH_FAULT_LAYOUT 3u\n")
    for((f,id)<-TypedColorFormat.formats.zipWithIndex){
      header.append(s"#define OPENGPU_TEXTURE_FORMAT_${f.name} ${id}u\n#define OPENGPU_TEXTURE_FORMAT_${f.name}_BYTES ${f.bytes}u\n")
    }
    header.append("\n#endif\n")
    val rows=TypedColorFormat.formats.zipWithIndex.map{case(f,id)=>s"    {\"id\":$id,\"name\":\"${f.name}\",\"bytes\":${f.bytes},\"colorType\":${f.kind},\"encoding\":${f.encoding}}"}.mkString(",\n")
    val json=s"{\n  \"version\":1,\"bits\":6,\"count\":36,\"storage\":\"TypedColorFormat\",\n  \"formats\":[\n$rows\n  ]\n}\n"
    for((name,value)<-Seq(paths.headOption.getOrElse("driver/opengpu_texture_image_format_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/texture-image-format-v1.json")->json)){
      val p=Paths.get(name)
      if(checking)require(Files.isRegularFile(p) && Files.readString(p,UTF_8)==value,s"texture format ABI differs: $p")
      else{Option(p.getParent).foreach(q=>Files.createDirectories(q));Files.writeString(p,value,UTF_8)}
    }
    println(s"TEXTURE_IMAGE_FORMAT_ABI formats=${TypedColorFormat.formats.size} checked=$checking")
  }
}

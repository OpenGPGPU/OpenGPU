package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import java.util.Locale
import opengpu.graphics._

object EmitTypedFragmentStateAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitTypedFragmentStateAbi [header-path] [json-path] [--check]")
    var fields=Seq.empty[(String,Int,Int,Boolean)]
    class Describe extends RawModule {
      val d=Wire(new TypedFragmentState(FragmentShaderConfig()));d:=0.U.asTypeOf(d)
      val fs=TypedFragmentStateLayout.fields(d);NativeTypedGraphicsLayout.check(d,fs,TypedFragmentStateLayout.words)
      fields=fs.map(f=>(f.name,f.word,f.width,f.value.isInstanceOf[SInt]))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_TYPED_FRAGMENT_STATE_"
    val header=new StringBuilder("/* Generated by EmitTypedFragmentStateAbi. Explicit little-endian words.\n"+
      " * Narrow signed fields sign-extend; other padding/reserved words are zero.\n"+
      " * Engine0 uses fragment.scratch; engines1..3 use scratch[0..2]. */\n"+
      "#ifndef OPENGPU_TYPED_FRAGMENT_STATE_ABI_H\n#define OPENGPU_TYPED_FRAGMENT_STATE_ABI_H\n#include <stdint.h>\n\n")
    header.append(FragmentInputAbi.header(prefix))
    for((name,value)<-Seq("MAGIC"->"0x47465301u","VERSION"->"1u","WORDS"->"128u","BYTES"->"512u","ENGINE_CAPACITY"->"4u",
      "HEADER_MAGIC_WORD"->"0u","HEADER_BYTES_WORD"->"1u","HEADER_VERSION_WORD"->"2u","HEADER_CAPACITY_WORD"->"3u",
      "HEADER_CONTEXT_WORD"->"4u","HEADER_PASS_WORD"->"5u","HEADER_GENERATION_WORD"->"6u","HEADER_HANDLE_WORD"->"7u"))header.append(s"#define $prefix$name $value\n")
    for((name,word,bits,_)<-fields){val upper=name.replace("[","").replace("]","").replace('.','_').toUpperCase(Locale.ROOT)
      require(upper.matches("[A-Z0-9_]+"));header.append(s"#define $prefix${upper}_WORD ${word}u\n#define $prefix${upper}_BITS ${bits}u\n")}
    header.append("struct opengpu_typed_fragment_state { uint32_t words[OPENGPU_TYPED_FRAGMENT_STATE_WORDS]; };\n\n#endif\n")
    val body=fields.map{case(name,word,bits,signed)=>s"    {\"name\":\"$name\",\"word\":$word,\"bits\":$bits,\"signed\":$signed}"}.mkString(",\n")
    val json=s"{\n  \"magic\":\"0x47465301\",\"version\":1,\"words\":128,\"bytes\":512,\"engines\":4,\n  \"fields\":[\n$body\n  ]\n}\n"
    for((name,contents)<-Seq(paths.headOption.getOrElse("driver/opengpu_typed_fragment_state_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/typed-fragment-state-v1.json")->json)){
      val path=Paths.get(name)
      if(checking)require(Files.isRegularFile(path) && Files.readString(path,UTF_8)==contents,s"fragment state ABI differs: $path")
      else{Option(path.getParent).foreach(p=>Files.createDirectories(p));Files.writeString(path,contents,UTF_8)}
    }
    println(s"TYPED_FRAGMENT_STATE_ABI version=1 bytes=512 fields=${fields.size} checked=$checking")
  }
}

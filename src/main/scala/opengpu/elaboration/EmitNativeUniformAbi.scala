package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import java.util.Locale
import opengpu.graphics._

/** Describe uniform records and instruction encodings. Constants alone do not
  * advertise native availability or replace runtime discovery.
  */
object EmitNativeUniformAbi {
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitNativeUniformAbi [header-path] [json-path] [--check]")
    var schemas=Seq.empty[(String,Int,BigInt,Seq[(String,Int,Int)])]
    class Describe extends RawModule {
      val root=Wire(new ShaderUniformRootRecord);root:=0.U.asTypeOf(root)
      val binding=Wire(new ShaderUniformBindingRecord);binding:=0.U.asTypeOf(binding)
      def describe(name: String,d: Data,words: Int,magic: BigInt,fs: Seq[NativeTypedGraphicsLayout.Field]): Unit={
        NativeTypedGraphicsLayout.check(d,fs,words);schemas=schemas:+((name,words,magic,fs.map(f=>(f.name,f.word,f.width))))
      }
      describe("root",root,16,ShaderUniformRootLayout.magic,ShaderUniformRootLayout.fields(root))
      describe("binding",binding,16,ShaderUniformBindingLayout.magic,ShaderUniformBindingLayout.fields(binding))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_UNIFORM_"
    val header=new StringBuilder("/* Generated by EmitNativeUniformAbi. Little-endian 32-bit words.\n * Narrow-field padding and all reserved words must be zero. */\n"+
      "#ifndef OPENGPU_UNIFORM_ABI_H\n#define OPENGPU_UNIFORM_ABI_H\n#include <stdint.h>\n\n")
    for((name,value)<-Seq("VERSION"->1,"BLOCKS_PER_STAGE"->ShaderUniformLimits.blocksPerStage,"BINDINGS"->ShaderUniformLimits.bindings,
      "BLOCK_BYTES"->ShaderUniformLimits.blockBytes,"OFFSET_ALIGNMENT"->ShaderUniformLimits.offsetAlignment,
      "DEFAULT_VERTEX_COMPONENTS"->ShaderUniformLimits.defaultComponents(0),"DEFAULT_FRAGMENT_COMPONENTS"->ShaderUniformLimits.defaultComponents(1),
      "DEFAULT_BLOCK"->ShaderUniformLimits.defaultBlock,"TABLE_ALIGNMENT"->64,"DEFAULT_ALIGNMENT"->4,
      "STAGE_VERTEX"->0,"STAGE_FRAGMENT"->1))header.append(s"#define $prefix$name ${value}u\n")
    for((name,value)<-Seq("SCALAR_LOAD_BASE"->NativeUniformCapabilities.scalarLoadBase,"VECTOR_LOAD_BASE"->NativeUniformCapabilities.vectorLoadBase,
      "VECTOR_LOAD_UNMASKED_BASE"->NativeUniformCapabilities.vectorLoadUnmaskedBase)){
      val encoded=f"0x${value.toLong}%08xu";header.append(s"#define $prefix$name $encoded\n")
    }
    header.append(NativeUniformCapabilities.header(prefix))
    for((name,words,magic,fs)<-schemas){val p=prefix+name.toUpperCase(Locale.ROOT)+"_"
      header.append(s"#define ${p}MAGIC 0x${magic.toString(16)}u\n#define ${p}WORDS ${words}u\n#define ${p}BYTES ${words*4}u\n")
      for((field,word,bits)<-fs){val n=field.replace('.','_').toUpperCase(Locale.ROOT)
        header.append(s"#define $p${n}_WORD ${word}u\n#define $p${n}_BITS ${bits}u\n")}
      header.append(s"struct opengpu_uniform_$name { uint32_t words[${p}WORDS]; };\n\n")
    }
    header.append("#endif\n")
    val bodies=schemas.map{case(name,words,magic,fs)=>
      val fields=fs.map{case(n,w,b)=>s"{\"name\":\"$n\",\"word\":$w,\"bits\":$b,\"signed\":false}"}.mkString(",")
      s"    {\"name\":\"$name\",\"magic\":\"0x${magic.toString(16)}\",\"words\":$words,\"bytes\":${words*4},\"fields\":[$fields]}"
    }.mkString(",\n")
    val defaults=ShaderUniformLimits.defaultComponents.mkString(",")
    val json=s"{\n  \"version\":1,\"blocksPerStage\":12,\"bindings\":24,\"blockBytes\":16384,\"offsetAlignment\":256,\"defaultComponents\":[$defaults],\n  \"layouts\":[\n$bodies\n  ]\n}\n"
    for((name,body)<-Seq(paths.headOption.getOrElse("driver/opengpu_uniform_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/native-uniform-v1.json")->json)){
      val p=Paths.get(name)
      if(checking)require(Files.isRegularFile(p) && Files.readString(p,UTF_8)==body,s"uniform ABI differs: $p")
      else{Option(p.getParent).foreach(x=>Files.createDirectories(x));Files.writeString(p,body,UTF_8)}
    }
    println(s"UNIFORM_ABI layouts=${schemas.size} checked=$checking")
  }
}

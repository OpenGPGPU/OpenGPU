package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import java.util.Locale
import opengpu.graphics._

/** Generate the software wire contract from the same fields the GIU1 reader receives. */
object EmitShaderImageAbi {
  def main(args: Array[String]): Unit = {
    val checking = args.contains("--check")
    val paths = args.filterNot(_ == "--check")
    require(paths.length <= 2, "EmitShaderImageAbi [header-path] [json-path] [--check]")
    var fields = Seq.empty[(String, Int, Int)]
    class Describe extends RawModule {
      val d = Wire(new ShaderImageBindingSnapshot)
      d := 0.U.asTypeOf(d)
      val fs = ShaderImageDescriptorLayout.fields(d)
      NativeTypedGraphicsLayout.check(d, fs, ShaderImageDescriptorLayout.words)
      fields = fs.map(f => (f.name, f.word, f.width))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix = "OPENGPU_SHADER_IMAGE_"
    val magic = ShaderImageDescriptorLayout.magic.toString(16)
    val words = ShaderImageDescriptorLayout.words
    val bytes = ShaderImageDescriptorLayout.bytes
    val h = new StringBuilder("/* Generated by EmitShaderImageAbi. GIU1 little-endian wire layout.\n" +
      " * Reserved words and unused field bits are zero. This does not advertise a device capability. */\n" +
      "#ifndef OPENGPU_SHADER_IMAGE_ABI_H\n#define OPENGPU_SHADER_IMAGE_ABI_H\n#include <stdint.h>\n\n")
    for ((name, value) <- Seq("MAGIC" -> s"0x${magic}u", "VERSION" -> "1u",
      "WORDS" -> s"${words}u", "BYTES" -> s"${bytes}u", "TABLE_ALIGNMENT" -> "64u"))
      h.append(s"#define $prefix$name $value\n")
    for ((name, word, bits) <- fields) {
      val upper = name.replace('.', '_').toUpperCase(Locale.ROOT)
      require(upper.matches("[A-Z0-9_]+") && bits > 0 && bits <= 33)
      h.append(s"#define $prefix${upper}_WORD ${word}u\n#define $prefix${upper}_BITS ${bits}u\n")
    }
    h.append("\n/* Only the first word of a field is an editable field address. */\n" +
      "static inline unsigned opengpu_shader_image_field_bits(unsigned word)\n{\n    switch (word) {\n")
    for ((_, word, bits) <- fields) h.append(s"    case ${word}u: return ${bits}u;\n")
    h.append("    default: return 0u;\n    }\n}\n\n" +
      "static inline uint32_t opengpu_shader_image_word_mask(unsigned word)\n{\n    switch (word) {\n")
    for ((_, word, bits) <- fields; index <- 0 until ((bits + 31) / 32)) {
      val mask = ((BigInt(1) << math.min(32, bits - index * 32)) - 1).toString(16)
      h.append(s"    case ${word + index}u: return UINT32_C(0x$mask);\n")
    }
    h.append("    default: return 0u;\n    }\n}\n\n#endif\n")
    val body = fields.map { case (name, word, bits) =>
      s"    {\"name\":\"$name\",\"word\":$word,\"bits\":$bits,\"signed\":false}"
    }.mkString(",\n")
    val json = s"{\n  \"magic\":\"0x$magic\",\"version\":1,\"words\":$words,\"bytes\":$bytes,\"tableAlignment\":64,\n  \"fields\":[\n$body\n  ]\n}\n"
    for ((name, contents) <- Seq(
      paths.headOption.getOrElse("driver/opengpu_shader_image_abi.h") -> h.toString,
      paths.lift(1).getOrElse("docs/abi/shader-image-v1.json") -> json)) {
      val path = Paths.get(name)
      if (checking) require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == contents,
        s"shader image ABI differs: $path")
      else {
        Option(path.getParent).foreach(p => Files.createDirectories(p))
        Files.writeString(path, contents, UTF_8)
      }
    }
    println(s"SHADER_IMAGE_ABI version=1 bytes=$bytes fields=${fields.size} checked=$checking")
  }
}

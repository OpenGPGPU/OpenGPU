package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import opengpu.graphics._
import java.util.Locale

/** Published source schemas, independent from Bundle packing and GNC1..4. */
object EmitNativeLayeredGraphicsAbi {
  private case class Field(name:String,word:Int,bits:Int,signed:Boolean){val words=(bits+31)/32}
  private case class Schema(name:String,words:Int,magic:BigInt,version:Int,fields:Seq[Field])
  def main(args:Array[String]):Unit={
    val check=args.contains("--check");val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitNativeLayeredGraphicsAbi [header] [json] [--check]")
    var schemas=Seq.empty[Schema]
    class Describe extends RawModule {
      val job=Wire(new NativeLayeredGraphicsJobRecord);job:=0.U.asTypeOf(job)
      val frame=Wire(new NativeLayeredGraphicsFrameRecord);frame:=0.U.asTypeOf(frame)
      val result=Wire(new NativeLayeredCompletionCapture);result:=0.U.asTypeOf(result)
      def describe(name:String,words:Int,magic:BigInt,version:Int,d:Data,fs:Seq[NativeTypedGraphicsLayout.Field]):Schema={
        NativeTypedGraphicsLayout.check(d,fs,words)
        Schema(name,words,magic,version,fs.sortBy(_.word).map(f=>Field(f.name,f.word,f.width,f.value.isInstanceOf[SInt])))
      }
      val completeFields=NativeLayeredCompletionEncoding.fields(result);NativeLayeredCompletionEncoding.check(result,completeFields)
      schemas=Seq(describe("job",128,NativeLayeredGraphicsLayout.jobMagic,2,job,NativeLayeredGraphicsLayout.jobFields(job)),
        describe("frame",512,NativeLayeredGraphicsLayout.frameMagic,3,frame,NativeLayeredGraphicsLayout.frameFields(frame)),
        Schema("completion",NativeLayeredGraphicsLayout.completionWords,NativeLayeredGraphicsLayout.completionMagic,2,
          completeFields.map(f=>Field(f.name,f.word,f.width,f.value.isInstanceOf[SInt]))))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_NATIVE_LAYERED_"
    val header=new StringBuilder("/* Generated by EmitNativeLayeredGraphicsAbi. Fixed complete native capacities. */\n"+
      "#ifndef OPENGPU_NATIVE_LAYERED_ABI_H\n#define OPENGPU_NATIVE_LAYERED_ABI_H\n"+
      "#ifdef __KERNEL__\ntypedef unsigned int opengpu_native_layered_word;\n#else\n#include <stdint.h>\ntypedef uint32_t opengpu_native_layered_word;\n#endif\n\n")
    header.append(s"#define ${prefix}CAP_MAGIC 0x${NativeBinnedGraphicsCapabilities.layeredMagic.toString(16)}u\n")
    for((s,index)<-schemas.zipWithIndex){val kind=s.name.toUpperCase(Locale.ROOT)
      header.append(s"#define $prefix${kind}_MAGIC 0x${s.magic.toString(16)}u\n#define $prefix${kind}_VERSION ${s.version}u\n"+
        s"#define $prefix${kind}_WORDS ${s.words}u\n#define $prefix${kind}_BYTES ${s.words*4}u\n#define $prefix${kind}_KIND ${index}u\n")
      for(f<-s.fields){val name=f.name.replace("[","").replace("]","").replace('.','_').toUpperCase(Locale.ROOT)
        header.append(s"#define $prefix${kind}_${name}_WORD ${f.word}u\n#define $prefix${kind}_${name}_BITS ${f.bits}u\n")}
      header.append(s"struct opengpu_native_layered_${s.name} { opengpu_native_layered_word words[$prefix${kind}_WORDS]; };\n\n")
    }
    header.append("/* Canonical bytes only; semantic view permissions, lifetime, layout/link\n * compatibility and physical aliases require the complete owner admission. */\n"+
      "static inline int opengpu_native_layered_wire_valid(unsigned kind, const opengpu_native_layered_word *w, unsigned count)\n{\n    unsigned i;\n    if (!w) return 0;\n    switch (kind) {\n")
    for((s,index)<-schemas.zipWithIndex){header.append(s"    case ${index}u:\n        if (count != ${s.words}u || w[0] != 0x${s.magic.toString(16)}u || w[1] != ${s.words*4}u || w[2] != ${s.version}u) return 0;\n"+
        "        for (i = 3; i < count; ++i) {\n            switch (i) {\n")
      for(f<-s.fields;i<-0 until f.words){
        header.append(s"            case ${f.word+i}u:")
        if(i==f.words-1 && f.bits%32!=0){val n=f.bits%32;val low=(BigInt(1)<<n)-1;val high=BigInt("ffffffff",16)^low
          if(f.signed)header.append(s" if ((w[i] & 0x${high.toString(16)}u) != ((w[i] & 0x${(BigInt(1)<<(n-1)).toString(16)}u) ? 0x${high.toString(16)}u : 0u)) return 0;")
          else header.append(s" if (w[i] & 0x${high.toString(16)}u) return 0;")
        }
        header.append(" break;\n")
      }
      header.append("            default: if (w[i]) return 0; break;\n            }\n        }\n        return 1;\n")
    }
    header.append("    default: return 0;\n    }\n}\n#endif\n")
    val json=schemas.map{s=>val fields=s.fields.map(f=>s"{\"name\":\"${f.name}\",\"word\":${f.word},\"bits\":${f.bits},\"signed\":${f.signed}}").mkString(",\n")
      s"\"${s.name}\":{\"magic\":\"0x${s.magic.toString(16)}\",\"version\":${s.version},\"words\":${s.words},\"bytes\":${s.words*4},\"fields\":[\n$fields\n]}"}.mkString("{\n",",\n","\n}\n")
    EmitCommandAbi.writeOrCheck(check,Seq(paths.headOption.getOrElse("driver/opengpu_native_layered_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/native-layered-graphics-v2.json")->json))
    println(s"NATIVE_LAYERED_ABI layouts=${schemas.size} fields=${schemas.map(_.fields.size).sum} completionBytes=${NativeLayeredGraphicsLayout.completionBytes} checked=$check")
  }
}

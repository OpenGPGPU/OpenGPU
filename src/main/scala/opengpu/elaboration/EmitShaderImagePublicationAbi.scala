package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import java.util.Locale
import opengpu.graphics._

/** Generate the GIR1 root layout from the hardware admission fields. */
object EmitShaderImagePublicationAbi {
  def main(args: Array[String]): Unit = {
    val checking = args.contains("--check")
    val paths = args.filterNot(_ == "--check")
    require(paths.length <= 2, "EmitShaderImagePublicationAbi [header-path] [json-path] [--check]")
    var fields = Seq.empty[(String, Int, Int)]
    class Describe extends RawModule {
      val root = Wire(new ShaderImagePublicationRoot); root := 0.U.asTypeOf(root)
      val fs = ShaderImagePublicationLayout.fields(root)
      NativeTypedGraphicsLayout.check(root, fs, ShaderImagePublicationLayout.words)
      fields = fs.map(f => (f.name, f.word, f.width))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix = "OPENGPU_SHADER_IMAGE_PUBLICATION_"
    val magic = ShaderImagePublicationLayout.magic.toString(16)
    val header = new StringBuilder("/* Generated by EmitShaderImagePublicationAbi. GIR1 little-endian wire layout.\n" +
      " * Reserved words and unused field bits are zero; this does not advertise a capability. */\n" +
      "#ifndef OPENGPU_SHADER_IMAGE_PUBLICATION_ABI_H\n#define OPENGPU_SHADER_IMAGE_PUBLICATION_ABI_H\n#include <stdint.h>\n\n")
    for ((name, value) <- Seq("MAGIC" -> s"0x${magic}u", "VERSION" -> "1u",
      "WORDS" -> s"${ShaderImagePublicationLayout.words}u", "BYTES" -> s"${ShaderImagePublicationLayout.bytes}u",
      "ALIGNMENT" -> "64u", "STAGE_FRAGMENT" -> s"${GraphicsStage.fragment}u"))
      header.append(s"#define $prefix$name $value\n")
    for ((name, word, bits) <- fields) {
      val upper = name.replace('.', '_').toUpperCase(Locale.ROOT)
      require(upper.matches("[A-Z0-9_]+"))
      header.append(s"#define $prefix${upper}_WORD ${word}u\n#define $prefix${upper}_BITS ${bits}u\n")
    }
    header.append("\nstruct opengpu_shader_image_publication { uint32_t words[OPENGPU_SHADER_IMAGE_PUBLICATION_WORDS]; };\n\n#endif\n")
    val body = fields.map { case (name, word, bits) =>
      s"    {\"name\":\"$name\",\"word\":$word,\"bits\":$bits,\"signed\":false}"
    }.mkString(",\n")
    val json = s"{\n  \"magic\":\"0x$magic\",\"version\":1,\"words\":${ShaderImagePublicationLayout.words},\"bytes\":${ShaderImagePublicationLayout.bytes},\"alignment\":64,\n  \"fields\":[\n$body\n  ]\n}\n"
    for ((name, contents) <- Seq(
      paths.headOption.getOrElse("driver/opengpu_shader_image_publication_abi.h") -> header.toString,
      paths.lift(1).getOrElse("docs/abi/shader-image-publication-v1.json") -> json)) {
      val path = Paths.get(name)
      if (checking) require(Files.isRegularFile(path) && Files.readString(path, UTF_8) == contents,
        s"image publication ABI differs: $path")
      else { Option(path.getParent).foreach(p => Files.createDirectories(p)); Files.writeString(path, contents, UTF_8) }
    }
    println(s"SHADER_IMAGE_PUBLICATION_ABI version=1 bytes=${ShaderImagePublicationLayout.bytes} fields=${fields.size} checked=$checking")
  }
}

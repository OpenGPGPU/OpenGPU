package opengpu.elaboration

import chisel3._
import circt.stage.ChiselStage
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import java.util.Locale
import opengpu.graphics._

/** Publish/check software word offsets from the explicit hardware layout.
  * No Bundle bit-packing or capacity-dependent offsets enter this ABI.
  */
object EmitNativeTypedGraphicsAbi {
  private case class AbiField(name: String,word: Int,bits: Int,signed: Boolean)
  private case class Schema(name: String,words: Int,magic: BigInt,fields: Seq[AbiField])
  def main(args: Array[String]): Unit={
    val checking=args.contains("--check")
    val paths=args.filterNot(_=="--check")
    require(paths.length<=2,"EmitNativeTypedGraphicsAbi [header-path] [json-path] [--check]")
    var schemas=Seq.empty[Schema]
    class Describe extends RawModule {
      import NativeTypedGraphicsLayout._
      val job=Wire(new NativeTypedGraphicsJob);job:=0.U.asTypeOf(job)
      val pass=Wire(new TypedTileImageDescriptor);pass:=0.U.asTypeOf(pass)
      val draw=Wire(new TypedTileRenderDraw(vertex,fragment));draw:=0.U.asTypeOf(draw)
      def schema(name: String,words: Int,magic: BigInt,d: Data,fs: Seq[NativeTypedGraphicsLayout.Field]): Schema={
        check(d,fs,words)
        Schema(name,words,magic,fs.sortBy(_.word).map(f=>AbiField(f.name,f.word,f.width,f.value.isInstanceOf[SInt])))
      }
      schemas=Seq(schema("job",jobWords,jobMagic,job,jobFields(job)),schema("pass",passWords,passMagic,pass,passFields(pass)),
        schema("draw",drawWords,drawMagic,draw,drawFields(draw)))
    }
    ChiselStage.emitCHIRRTL(new Describe)
    val prefix="OPENGPU_NATIVE_TYPED_"
    val header=new StringBuilder("/* Generated by EmitNativeTypedGraphicsAbi. Little-endian 32-bit words.\n"+
      " * Narrow unsigned fields use zero padding; narrow signed fields sign-extend.\n"+
      " * 33/64-bit fields occupy consecutive low/high words. Reserved words are zero.\n"+
      " * Descriptor bases and strides are 64-byte aligned. See NATIVE_TYPED_GRAPHICS_ABI.md. */\n"+
      "#ifndef OPENGPU_NATIVE_TYPED_ABI_H\n#define OPENGPU_NATIVE_TYPED_ABI_H\n#include <stdint.h>\n\n")
    header.append(s"#define ${prefix}VERSION ${NativeTypedGraphicsLayout.version}u\n")
    header.append(s"#define ${prefix}INPUT_VERSION ${VertexInputFormat.version}u\n")
    header.append(NativeVertexInputCapabilities.header(prefix))
    header.append(FragmentInputAbi.header(prefix))
    for((name,id)<-VertexInputFormat.formats)header.append(s"#define ${prefix}INPUT_FORMAT_$name ${id}u\n")
    for((name,value)<-Seq("OPCODE"->"7u","DISCOVERY"->"0x68u","CAPABILITIES"->"0x160u","CAPABILITY_MAGIC"->"0x47544301u",
      "CAP_LOCAL_PAYLOAD"->"1u","CAP_PHYSICAL_IMAGES"->"2u","CAP_SHADER_ABI2"->"4u",
      "HEADER_MAGIC_WORD"->"0u","HEADER_BYTES_WORD"->"1u","HEADER_VERSION_WORD"->"2u"))header.append(s"#define $prefix$name $value\n")
    for(s<-schemas){val upper=s.name.toUpperCase(Locale.ROOT)
      header.append(s"\n#define $prefix${upper}_MAGIC 0x${s.magic.toString(16)}u\n#define $prefix${upper}_WORDS ${s.words}u\n#define $prefix${upper}_BYTES ${s.words*4}u\n")
      for(f<-s.fields){require(f.name.matches("[A-Za-z0-9_.]+"));val name=f.name.replace('.','_').toUpperCase(Locale.ROOT)
        header.append(s"#define $prefix${upper}_${name}_WORD ${f.word}u\n#define $prefix${upper}_${name}_BITS ${f.bits}u\n")}
      header.append(s"struct opengpu_native_typed_${s.name} { uint32_t words[$prefix${upper}_WORDS]; };\n")
    }
    header.append("\n#endif\n")
    val json=schemas.map{s=>
      val fields=s.fields.map(f=>s"    {\"name\":\"${f.name}\",\"word\":${f.word},\"bits\":${f.bits},\"signed\":${f.signed}}").mkString(",\n")
      s"  \"${s.name}\": {\"magic\":\"0x${s.magic.toString(16)}\",\"words\":${s.words},\"bytes\":${s.words*4},\"fields\":[\n$fields\n  ]}"
    }.mkString("{\n",",\n","\n}\n")
    val outputs=Seq(paths.headOption.getOrElse("driver/opengpu_native_typed_abi.h")->header.toString,
      paths.lift(1).getOrElse("docs/abi/native-typed-graphics-v1.json")->json)
    for((name,contents)<-outputs){val path=Paths.get(name)
      if(checking)require(Files.isRegularFile(path) && Files.readString(path,UTF_8)==contents,s"native ABI differs: $path")
      else {Option(path.getParent).foreach(p=>Files.createDirectories(p));Files.writeString(path,contents,UTF_8)}
    }
    println(s"NATIVE_TYPED_ABI version=${NativeTypedGraphicsLayout.version} layouts=${schemas.size} fields=${schemas.map(_.fields.size).sum} checked=$checking")
  }
}

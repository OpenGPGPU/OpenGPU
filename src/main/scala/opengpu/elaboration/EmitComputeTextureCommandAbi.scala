package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Paths}
import opengpu.graphics.ComputeTextureCommandMmioRegs

object EmitComputeTextureCommandAbi {
  def main(args: Array[String]): Unit = {
    require(args.isEmpty || args.toSeq == Seq("--check"))
    val r=ComputeTextureCommandMmioRegs
    require(r.controlMask==BigInt("301",16))
    val fields=Seq("CONTROL","ROOT","CONTEXT","PASS","GENERATION","MAGIC")
    val header="/* Generated by EmitComputeTextureCommandAbi. GTM1 command transport. */\n"+
      "#ifndef OPENGPU_COMPUTE_TEXTURE_COMMAND_ABI_H\n#define OPENGPU_COMPUTE_TEXTURE_COMMAND_ABI_H\n"+
      s"#define OPENGPU_COMPUTE_TEXTURE_COMMAND_BASE 0x${r.base.toHexString}u\n"+
      s"#define OPENGPU_COMPUTE_TEXTURE_COMMAND_END 0x${r.end.toHexString}u\n"+
      s"#define OPENGPU_COMPUTE_TEXTURE_COMMAND_MAGIC_VALUE 0x${r.magic.toString(16)}u\n"+
      s"#define OPENGPU_COMPUTE_TEXTURE_COMMAND_WORDS ${fields.size-1}u\n"+
      fields.zipWithIndex.map { case(name,i)=>
        s"#define OPENGPU_COMPUTE_TEXTURE_COMMAND_REG_$name 0x${(r.base+i*4).toHexString}u\n"
      }.mkString+"#define OPENGPU_COMPUTE_TEXTURE_COMMAND_ENABLE 1u\n"+
      "#define OPENGPU_COMPUTE_TEXTURE_COMMAND_VERSION_SHIFT 8u\n#endif\n"
    val path=Paths.get("driver/opengpu_compute_texture_command_abi.h")
    if(args.nonEmpty)require(Files.isRegularFile(path)&&Files.readString(path,UTF_8)==header)
    else Files.writeString(path,header,UTF_8)
  }
}

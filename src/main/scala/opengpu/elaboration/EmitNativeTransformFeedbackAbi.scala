package opengpu.elaboration

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files,Paths}
import opengpu.graphics.{NativeTransformFeedbackCapabilities=>Caps,NativeTransformFeedbackRecord=>Record}

object EmitNativeTransformFeedbackAbi {
  def main(args: Array[String]): Unit={
    require(args.isEmpty || args.toSeq==Seq("--check"),"EmitNativeTransformFeedbackAbi [--check]")
    val checking=args.nonEmpty
    val fields=Seq("MAGIC"->0,"BYTES"->1,"VERSION"->2,"ACTION"->3,"CONTEXT"->4,"COOKIE"->5,
      "PROGRAM"->6,"KIND"->7,"LAYOUT_FLAGS"->8,"BUFFERS"->9,"COMPONENTS"->10,"VIEWS"->16,
      "OFFSETS"->28,"PRIMITIVES"->36,"VERTICES"->38,"STATE_STATUS"->40,"ROOT"->41,
      "OPERATION_STATUS"->42,"OPERATION_FLAGS"->43,"SELECTORS"->48)
    val actions=Seq("BEGIN"->0,"END"->1,"PAUSE"->2,"RESUME"->3,"RESTORE"->4,"EVICT"->5)
    val features=Seq("SCOPED_OBJECTS","PAUSED_CHECKPOINTS","RAW_PRE_FLAT","ACKNOWLEDGED_COUNTS",
      "RASTER_DISCARD","SCOPED_PUBLICATION_RECOVERY","COMMIT_LINE_LAST","REQUIRED_CAPTURE_LEASE")
    val constants=Seq("CAPABILITIES"->s"0x${Caps.base.toHexString}u",
      "CAPABILITY_MAGIC"->s"0x${Caps.magic.toString(16)}u","CAPABILITY_WORDS"->s"${Caps.wordCount}u",
      "OPCODE"->s"${Caps.opcode}u","RECORD_MAGIC"->s"0x${Record.magic.toString(16)}u",
      "RECORD_BYTES"->s"${Record.bytes}u","RECORD_WORDS"->s"${Record.words}u","RECORD_VERSION"->"1u",
      "RECORD_ALIGNMENT"->"64u","ACTIVE_OBJECTS"->"8u","BINDINGS"->"4u","INTERLEAVED_COMPONENTS"->"64u",
      "SEPARATE_COMPONENTS"->"4u","PUBLIC_ACTION_MASK"->"0x3fu","OPCODE_HIGH_BIT"->"16u",
      "RENDER_RASTER_DISCARD"->s"(1u << ${Caps.rasterDiscardFlag})",
      "RENDER_CAPTURE"->s"(1u << ${Caps.captureFlag})","LAYOUT_INTERLEAVED"->"1u","LAYOUT_PAUSED"->"2u",
      "DATA_ACTIVE"->"1u","DATA_RECORD_COMPLETE"->"2u","DATA_APPLIED"->"4u") ++
      actions.map{case(n,v)=>s"ACTION_$n"->s"${v}u"} ++
      fields.map{case(n,v)=>s"${n}_WORD"->s"${v}u"} ++
      features.zipWithIndex.map{case(n,i)=>s"FEATURE_$n"->s"(1u << $i)"}
    val header="/* Generated by EmitNativeTransformFeedbackAbi. GFC1/GTF1, little-endian words. */\n"+
      "#ifndef OPENGPU_TRANSFORM_FEEDBACK_ABI_H\n#define OPENGPU_TRANSFORM_FEEDBACK_ABI_H\n#include <stdint.h>\n#include <stddef.h>\n\n"+
      constants.map{case(n,v)=>s"#define OPENGPU_TF_$n $v\n"}.mkString+
      "\nstruct opengpu_transform_feedback_view { uint32_t base, limit_lo, limit_hi; };\n"+
      "struct opengpu_transform_feedback_offset { uint32_t lo, hi; };\n"+
      "struct opengpu_transform_feedback_record {\n"+
      "    uint32_t magic, bytes, version, action, context, cookie, program, kind;\n"+
      "    uint32_t layout_flags, buffers, components[4], reserved14[2];\n"+
      "    struct opengpu_transform_feedback_view views[4];\n"+
      "    struct opengpu_transform_feedback_offset offsets[4];\n"+
      "    uint32_t primitives_lo, primitives_hi, vertices_lo, vertices_hi;\n"+
      "    uint32_t state_status, root, operation_status, operation_flags, reserved44[4];\n"+
      "    uint32_t selectors[64], reserved112[16];\n};\n"+
      "/* Clear operation_status/operation_flags before every command. A failed\n"+
      " * unified completion invalidates the record even if some bytes changed.\n"+
      " * SOURCE_STRIDE witnesses program for opcode12 and cookie for opcode7. */\n"+
      "#if defined(__cplusplus)\n#define OPENGPU_TF_ASSERT static_assert\n#else\n#define OPENGPU_TF_ASSERT _Static_assert\n#endif\n"+
      "OPENGPU_TF_ASSERT(sizeof(struct opengpu_transform_feedback_record)==512, \"GTF1 size\");\n"+
      fields.filterNot{case(n,_)=>Set("LAYOUT_FLAGS","STATE_STATUS","OPERATION_STATUS","OPERATION_FLAGS")(n)}.map{case(n,i)=>
        val member=n.toLowerCase(java.util.Locale.ROOT) match {
          case "primitives"=>"primitives_lo";case "vertices"=>"vertices_lo";case v=>v
        }
        s"OPENGPU_TF_ASSERT(offsetof(struct opengpu_transform_feedback_record,$member)==${i*4}, \"GTF1 $member\");\n"
      }.mkString+
      Seq("layout_flags"->8,"state_status"->40,"operation_status"->42,"operation_flags"->43).map{case(n,i)=>
        s"OPENGPU_TF_ASSERT(offsetof(struct opengpu_transform_feedback_record,$n)==${i*4}, \"GTF1 $n\");\n"
      }.mkString+"#undef OPENGPU_TF_ASSERT\n#endif\n"
    val json="{\n  \"version\":1,\n"+
      s"  \"capability_base\":${Caps.base},\n  \"capability_magic\":\"0x${Caps.magic.toString(16)}\",\n"+
      s"  \"capability_words_max_profile\":[${Caps.words(69).map(v=>s"\"0x${v.toString(16)}\"").mkString(",")}],\n"+
      "  \"source_words_by_profile\":\"5+4*native_vertex_varyings\",\n"+
      s"  \"record_magic\":\"0x${Record.magic.toString(16)}\",\n  \"record_bytes\":${Record.bytes},\n"+
      "  \"record_alignment\":64,\n  \"allocation_limit_bits\":33,\n  \"active_objects\":8,\n"+
      "  \"bindings\":4,\n  \"interleaved_components\":64,\n  \"separate_components\":4,\n"+
      s"  \"actions\":{${actions.map{case(n,v)=>s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$v"}.mkString(",")}},\n"+
      s"  \"record_words\":{${fields.map{case(n,v)=>s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$v"}.mkString(",")}},\n"+
      s"  \"feature_bits\":{${features.zipWithIndex.map{case(n,i)=>s"\"${n.toLowerCase(java.util.Locale.ROOT)}\":$i"}.mkString(",")}},\n"+
      "  \"control_command\":{\"opcode\":12,\"address\":\"SOURCE\",\"limit_low\":\"DESTINATION\",\"limit_high\":\"PATTERN[0]\",\"bytes\":512,\"context\":\"WIDTH\",\"cookie\":\"HEIGHT\",\"program\":\"SOURCE_STRIDE\",\"flags\":0},\n"+
      "  \"render_command\":{\"opcode\":7,\"context\":\"WIDTH\",\"program\":\"HEIGHT\",\"cookie\":\"SOURCE_STRIDE\",\"raster_discard_flag_bit\":3,\"require_capture_flag_bit\":4},\n"+
      "  \"completion_opcode_high_bit\":16,\n  \"completion_and_record_flags\":{\"active\":0,\"record_complete\":1,\"applied\":2},\n"+
      "  \"input_zero_words\":[14,15,42,43,44,45,46,47,112,113,114,115,116,117,118,119,120,121,122,123,124,125,126,127],\n"+
      "  \"commit_line\":2,\n  \"failed_completion_invalidates_record\":true,\n"+
      "  \"capture_lease\":\"running context/full-root/cookie/program/kind required; capture-off requires inactive or paused scope\"\n}\n"
    for((name,text)<-Seq("driver/opengpu_transform_feedback_abi.h"->header,"docs/abi/native-transform-feedback-v1.json"->json)){
      val path=Paths.get(name)
      if(checking)require(Files.isRegularFile(path) && Files.readString(path,UTF_8)==text,s"feedback ABI differs: $path")
      else{Files.createDirectories(path.getParent);Files.writeString(path,text,UTF_8)}
    }
    println(s"NATIVE_TRANSFORM_FEEDBACK_ABI checked=$checking recordBytes=${Record.bytes} objects=8 opcode=12")
  }
}

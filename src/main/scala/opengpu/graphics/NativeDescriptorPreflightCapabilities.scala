package opengpu.graphics

/** GNP1 is a hardware metadata preflight contract, independent of GAB1's
  * advanced transport. Presence requires ABI>=2 and GCR1 bit16. Every GND and
  * referenced GFS is checked before any begin/VS; accepted memory and controls
  * drain before completion. Raw callers still own immutable publication and
  * physical/resource lifetime. CPU isolation is a separate driver contract.
  */
object NativeDescriptorPreflightCapabilities {
  val base=0x4e0;val wordCount=8;val end=base+wordCount*4
  val magic=BigInt("474e5001",16)
  val allDraws=1;val allReferencedStates=2;val typedCompatibility=4;val completeDrain=8
  val features=allDraws|allReferencedStates|typedCompatibility|completeDrain
  val fields=Seq("MAGIC","WORDS","JOB_BYTES","FRAME_BYTES","DRAW_BYTES","STATE_BYTES","FEATURES","RESERVED")
  val words=Seq[BigInt](magic,wordCount,NativeBinnedGraphicsLayout.jobBytes,
    NativeBinnedGraphicsLayout.frameBytes,NativeBinnedGraphicsLayout.drawBytes,TypedFragmentStateLayout.bytes,features,0)
  require(base==NativeAdvancedBlendCapabilities.end && end<=0x800 && (base&31)==0)
  require(words.size==wordCount && words.forall(w=>w>=0 && w<(BigInt(1)<<32)))
  def header: String={
    val p="OPENGPU_NATIVE_PREFLIGHT_"
    "/* Generated by EmitNativeDescriptorPreflightAbi. Hardware metadata contract only. */\n"+
      "#ifndef OPENGPU_NATIVE_PREFLIGHT_ABI_H\n#define OPENGPU_NATIVE_PREFLIGHT_ABI_H\n"+
      Seq("CAPABILITIES"->BigInt(base),"MAGIC"->magic,"WORDS"->BigInt(wordCount),
        "JOB_BYTES"->BigInt(NativeBinnedGraphicsLayout.jobBytes),"FRAME_BYTES"->BigInt(NativeBinnedGraphicsLayout.frameBytes),
        "DRAW_BYTES"->BigInt(NativeBinnedGraphicsLayout.drawBytes),"STATE_BYTES"->BigInt(TypedFragmentStateLayout.bytes),
        "FEATURES"->BigInt(features),"ALL_DRAWS"->BigInt(allDraws),"ALL_REFERENCED_STATES"->BigInt(allReferencedStates),
        "TYPED_COMPATIBILITY"->BigInt(typedCompatibility),"COMPLETE_DRAIN"->BigInt(completeDrain))
        .map{case(n,v)=>s"#define $p$n 0x${v.toString(16)}u\n"}.mkString+
      fields.zipWithIndex.map{case(n,i)=>s"#define ${p}REG_$n 0x${(base+4*i).toHexString}u\n"}.mkString+"#endif\n"
  }
}

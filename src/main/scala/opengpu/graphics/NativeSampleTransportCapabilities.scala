package opengpu.graphics

/** GSS1 describes the raw full-plane native shader transport. It deliberately
  * does not claim API state, GLSL lowering or dynamic interpolation services.
  */
object NativeSampleTransportCapabilities {
  val base=0x520;val wordCount=8;val end=base+4*wordCount
  val presence=1<<20
  val magic=BigInt("47535301",16)
  val sampleId=1;val samplePosition=2;val sampleMaskIn=4;val sampleMaskOut=8;val fullPlane=16
  val features=sampleId|samplePosition|sampleMaskIn|sampleMaskOut|fullPlane
  val inputVersions=(1<<6)|(1<<7)
  // Exact maxima, one byte each: samples, varying slots, MRTs, input arrays.
  val limits=BigInt("4d041004",16)
  val outputControlMask=0x7ff;val sampleModes=7
  val fields=Seq("MAGIC","WORDS","VERSION","FEATURES","INPUT_VERSIONS","LIMITS","OUTPUT_CONTROL_MASK","SAMPLE_MODES")
  val words=Seq(magic,BigInt(wordCount),BigInt(1),BigInt(features),BigInt(inputVersions),
    limits,BigInt(outputControlMask),BigInt(sampleModes))
  require(words.size==wordCount && words.forall(w=>w>=0 && w<(BigInt(1)<<32)))
  def header:String={
    val p="OPENGPU_NATIVE_SAMPLE_TRANSPORT_"
    "/* Generated by EmitNativeSampleTransportAbi. Raw native transport, not GLES conformance. */\n"+
      "#ifndef OPENGPU_NATIVE_SAMPLE_TRANSPORT_ABI_H\n#define OPENGPU_NATIVE_SAMPLE_TRANSPORT_ABI_H\n"+
      Seq("CAPABILITIES"->BigInt(base),"PRESENCE"->BigInt(presence)).map{case(n,v)=>s"#define $p$n 0x${v.toString(16)}u\n"}.mkString+
      fields.zip(words).map{case(n,v)=>s"#define $p$n 0x${v.toString(16)}u\n"}.mkString+
      fields.zipWithIndex.map{case(n,i)=>s"#define ${p}REG_$n 0x${(base+4*i).toHexString}u\n"}.mkString+"#endif\n"
  }
}

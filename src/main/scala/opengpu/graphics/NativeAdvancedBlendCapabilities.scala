package opengpu.graphics

/** GAB1 describes an optional native transport, not a GLES/KHR capability.
  * ABI >= 2 hosts advertise its presence through GCR1 bit 15 before software
  * may read this block. GDB1 and all existing packet envelope versions stay
  * unchanged. Payload versions are independent of the internal blend state.
  */
object NativeAdvancedBlendCapabilities {
  val base=0x4c0;val wordCount=8;val end=base+wordCount*4
  val magic=BigInt("47414201",16)
  val drawPayloadVersion=3;val fragmentStatePayloadVersion=3
  val blendStateVersion=3
  require(blendStateVersion==TypedBlendState.advancedIndexedVersion)
  require(drawPayloadVersion==fragmentStatePayloadVersion)
  val payloadVersions=BigInt(1)<<drawPayloadVersion
  val equations=BigInt(0x7fff)
  val formats=TypedColorFormat.formats.zipWithIndex.filter(_._1.kind==0)
    .foldLeft(BigInt(0)){case(mask,(_,id))=>mask.setBit(id)}
  val parallelOwners=1;val sampleDestinations=2;val orderedDrawDrain=4
  val features=parallelOwners|sampleDestinations|orderedDrawDrain
  val fields=Seq("MAGIC","WORDS","PAYLOAD_VERSIONS","EQUATIONS","FORMATS_LOW","FORMATS_HIGH","FEATURES","RESERVED")
  val words=Seq[BigInt](magic,wordCount,payloadVersions,equations,
    formats&0xffffffffL,formats>>32,features,0)
  require(base>=AtomicCounterCommandMmioRegs.end && end<=0x800 && (base&31)==0)
  require(words.size==wordCount && words.forall(w=>w>=0 && w<(BigInt(1)<<32)))
  def header: String={
    val p="OPENGPU_NATIVE_ADVANCED_BLEND_"
    "/* Generated by EmitNativeAdvancedBlendAbi. Native transport only; no GL capability claim. */\n"+
      "#ifndef OPENGPU_NATIVE_ADVANCED_BLEND_ABI_H\n#define OPENGPU_NATIVE_ADVANCED_BLEND_ABI_H\n"+
      Seq("CAPABILITIES"->BigInt(base),"MAGIC"->magic,"WORDS"->BigInt(wordCount),
        "DRAW_PAYLOAD_VERSION"->BigInt(drawPayloadVersion),"FRAGMENT_STATE_PAYLOAD_VERSION"->BigInt(fragmentStatePayloadVersion),
        "BLEND_STATE_VERSION"->BigInt(blendStateVersion),"PAYLOAD_VERSIONS"->payloadVersions,"EQUATIONS"->equations,
        "FORMATS_LOW"->(formats&0xffffffffL),"FORMATS_HIGH"->(formats>>32),"FEATURES"->BigInt(features),
        "PARALLEL_OWNERS"->BigInt(parallelOwners),"SAMPLE_DESTINATIONS"->BigInt(sampleDestinations),"ORDERED_DRAW_DRAIN"->BigInt(orderedDrawDrain),
        "BUFFER_ADVANCED_SHIFT"->BigInt(27),"BUFFER_EQUATION_SHIFT"->BigInt(28),"BUFFER_EQUATION_MASK"->BigInt(15))
        .map{case(n,v)=>s"#define $p$n 0x${v.toString(16)}u\n"}.mkString+
      fields.zipWithIndex.map{case(n,i)=>s"#define ${p}REG_$n 0x${(base+4*i).toHexString}u\n"}.mkString+
      "#endif\n"
  }
}

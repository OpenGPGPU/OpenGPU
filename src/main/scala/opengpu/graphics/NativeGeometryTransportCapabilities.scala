package opengpu.graphics

/** GGS1 identifies the opt-in GNJ2/GNF3/GNY2 transport. It does not change
  * GUC1's VS/FS stages or advertise a GLSL/API geometry capability. */
object NativeGeometryTransportCapabilities {
  val base=0x500;val wordCount=8;val end=base+4*wordCount
  val magic=BigInt("47475301",16)
  val geometryPrograms=1;val geometryUniforms=2;val layeredImages=4
  val mixedOrdinary=8;val wideCompletion=16
  val features=geometryPrograms|geometryUniforms|layeredImages|mixedOrdinary|wideCompletion
  // Input vertices[3:0], invocations[9:4], vertices[18:10], varying
  // slots[23:19], maximum layer index[31:24]. All values are exact maxima.
  val limits=BigInt(6)|(BigInt(32)<<4)|(BigInt(256)<<10)|(BigInt(16)<<19)|(BigInt(255)<<24)
  // Completion words[15:0], emitted total components[31:16].
  val output=(BigInt(1024)<<16)|NativeLayeredGraphicsLayout.completionWords
  val fields=Seq("MAGIC","WORDS","FEATURES","JOB_MAGIC","FRAME_MAGIC","COMPLETION_MAGIC","LIMITS","OUTPUT")
  val words=Seq(magic,BigInt(wordCount),BigInt(features),NativeLayeredGraphicsLayout.jobMagic,
    NativeLayeredGraphicsLayout.frameMagic,NativeLayeredGraphicsLayout.completionMagic,limits,output)
  require(base==NativeDescriptorPreflightCapabilities.end && end<=0x800)
  require(words.size==wordCount && words.forall(w=>w>=0 && w<(BigInt(1)<<32)))
  def header:String={
    val p="OPENGPU_NATIVE_GEOMETRY_TRANSPORT_"
    "/* Generated by EmitNativeGeometryTransportAbi. Internal transport, not an API capability. */\n"+
      "#ifndef OPENGPU_NATIVE_GEOMETRY_TRANSPORT_ABI_H\n#define OPENGPU_NATIVE_GEOMETRY_TRANSPORT_ABI_H\n"+
      Seq("CAPABILITIES"->BigInt(base),"PRESENCE"->(BigInt(1)<<19)).map{case(n,v)=>s"#define $p$n 0x${v.toString(16)}u\n"}.mkString+
      fields.zip(words).map{case(n,v)=>s"#define $p$n 0x${v.toString(16)}u\n"}.mkString+
      fields.zipWithIndex.map{case(n,i)=>s"#define ${p}REG_$n 0x${(base+4*i).toHexString}u\n"}.mkString+"#endif\n"
  }
}

#!/usr/bin/env python3
"""Generate the independent GNQ4/5/6 BUILD and private host envelopes."""
import argparse
import json
from pathlib import Path
import re
from generate_tessellation_vertex_source_abi import rules

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'driver/opengpu_protected_tessellation_joint_abi.h'


def generate():
    s = json.loads((ROOT / 'docs/abi/protected-tessellation-joint-v2.json').read_text())
    if (s['version'], s['words'], s['bytes'], s['header']) != (2, 128, 512, [512, 2, 16, 16, 16, 4, 4]):
        raise ValueError('wrong joint envelope')
    host = dict(opcode=15, commandTag='0x474a0100', ownerLimitHighBit=0,
                domainShift=1, domainBits=2, rootAllocationBytes=4096,
                completionMagic='0x474e5a02', completionWords=16,
                completionHeadBase='0x180', completionHeadWords=12,
                completionTailBase='0x540', profileBase='0x550',
                profileMagic='0x474a5001', profileWords=4, profileDomains=7,
                profileRequiredFlags='0x7f', profileScalarFpuBit=7,
                profileAdvancedBlendBit=8, profileSamplesBit=9, profileFeedbackBit=10,
                ldsBase='0x10000000', ldsBytes=16384)
    if s['hostSubmission'] != host:
        raise ValueError('wrong private joint host envelope')
    if [(r['domain'], int(r['magic'], 16), int(r['sequenceMagic'], 16), r['sequenceVersion']) for r in s['records']] != [
            (d, 0x474e5104+i, 0x474e5407+i, 7+i) for i, d in enumerate(('isoline', 'triangle', 'quad'))]:
        raise ValueError('wrong joint domain pairing')
    expected = [('sequence.base',16,32),('sequence.count',17,32),('sequence.limit',18,33),
                ('sequence.stride',20,32),('frame.base',21,32),('frame.limit',22,33),
                ('identity.context',24,32),('identity.generation',25,32),('identity.pass',26,32),
                ('directory.version',27,32),('directory.base',28,32),('directory.limit',29,33),
                ('directory.count',31,32),('directory.bytes',32,32),('directory.entryBytes',33,32),
                ('directory.drawCount',34,32),('directory.invocationCount',35,32)]
    if s['fields'] != [dict(name=n,word=w,bits=b,signed=False) for n,w,b in expected]:
        raise ValueError('changed approved joint fields')
    directory = s['directory']
    if (directory['magic'],directory['version'],directory['headerBytes'],directory['entryBytes']) != ('0x47564d02',2,64,64):
        raise ValueError('changed exact directory')
    dh = [('magic',0,32),('bytes',1,32),('version',2,32),('entryBytes',3,32),
          ('drawCount',4,32),('invocationCount',5,32),('rangeCount',6,32),
          ('identity.context',7,32),('identity.pass',8,32),('identity.generation',9,32),
          ('attributes',10,32),('bindings',11,32),('varyings',12,32),('warps',13,32),('computeUnits',14,32)]
    de = [('sequenceIndex',0,32),('drawIndex',1,32),('invocationId',2,64),('flags',4,3),
          ('rangeOrdinal',5,32),('firstInstance',6,32),('instanceCount',7,32),
          ('firstInputPatch',8,32),('patchesPerInstance',9,32),('taskIdBase',10,32),('patchCount',11,32),
          ('source.base',12,32),('source.limit',13,33)]
    for key, fields in [('headerFields',dh),('entryFields',de)]:
        if directory[key] != [dict(name=n,word=w,bits=b,signed=False) for n,w,b in fields]:
            raise ValueError('changed exact directory fields')
        rules(directory[key],16)
    addresses = ['sequence.base','sequence.limit','frame.base','frame.limit','directory.base','directory.limit']
    if s['sourceAddressesZero'] != addresses:
        raise ValueError('changed source relocation fields')
    out = ['/* Generated by scripts/generate_protected_tessellation_joint_abi.py. */',
           '#ifndef OPENGPU_PROTECTED_TESSELLATION_JOINT_ABI_H',
           '#define OPENGPU_PROTECTED_TESSELLATION_JOINT_ABI_H',
           '#define OPENGPU_TESS_JOINT_BYTES 512u', '#define OPENGPU_TESS_JOINT_VERSION 2u']
    for name, value in host.items():
        macro = re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()
        out.append(f'#define OPENGPU_TESS_JOINT_HOST_{macro} {value}u')
    for r in s['records']:
        p = 'OPENGPU_TESS_JOINT_' + r['domain'].upper()
        out += [f'#define {p}_MAGIC {r["magic"]}u', f'#define {p}_SEQUENCE_MAGIC {r["sequenceMagic"]}u']
    for f in s['fields']:
        n = f['name'].replace('.', '_').upper()
        out += [f'#define OPENGPU_TESS_JOINT_{n}_WORD {f["word"]}u']
    for kind in ('headerFields','entryFields'):
        prefix = 'HEADER' if kind == 'headerFields' else 'ENTRY'
        for f in directory[kind]:
            name = f['name'].replace('.', '_').upper()
            out += [f'#define OPENGPU_TESS_DIRECTORY_{prefix}_{name}_WORD {f["word"]}u']
    values = rules([dict(name=f'header{i}',word=i,bits=32,signed=False) for i in range(8)] + s['fields'], 128)
    out += ['static const unsigned char opengpu_tess_joint_word_rules[128] = {']
    for i in range(0, 128, 16):
        out += ['    ' + ', '.join(map(str, values[i:i+16])) + ',']
    return '\n'.join(out + ['};', '#endif', ''])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    content = generate()
    if a.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            raise SystemExit('joint ABI generated header is stale')
    else:
        OUTPUT.write_text(content)
    print('GNQ4/5/6 exact joint ABI: ' + ('checked' if a.check else 'generated'))


if __name__ == '__main__':
    main()

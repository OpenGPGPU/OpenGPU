#!/usr/bin/env python3
"""Generate GVS1 and exact GNT7/8/9 canonical rules; no Scala or hardware enable."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'driver/opengpu_tessellation_vertex_source_abi.h'


def rules(fields, words):
    result = [0] * words
    names = set()
    for field in fields:
        name, word, bits = field['name'], field['word'], field['bits']
        if not isinstance(name, str) or name in names or type(word) is not int or type(bits) is not int or type(field['signed']) is not bool or not 1 <= bits <= 512:
            raise ValueError('invalid/duplicate ABI field')
        names.add(name)
        count = (bits + 31) // 32
        if word < 0 or word + count > words or word % 16 + count > 16:
            raise ValueError('field crosses record/cache line')
        for i in range(count):
            if result[word + i]:
                raise ValueError('overlapping ABI fields')
            width = min(32, bits - 32 * i)
            result[word + i] = width | (128 if field['signed'] and i == count - 1 and width < 32 else 0)
        if 'constant' in field and (type(field['constant']) is not int or not 0 <= field['constant'] < 2**bits):
            raise ValueError('constant exceeds field')
    return result


def generate(directory=None):
    directory = directory or ROOT / 'docs/abi'
    source = json.loads((directory / 'tessellation-vertex-source-v1.json').read_text())
    sequence = json.loads((directory / 'tessellation-vertex-sequence-v1.json').read_text())
    uniforms = json.loads((directory / sequence['uniformSchema']).read_text())
    if (source['magic'], source['version'], source['words'], source['bytes']) != ('0x47565301', 1, 128, 512):
        raise ValueError('unexpected GVS1 envelope')
    if (sequence['words'], sequence['bytes'], uniforms['words'], uniforms['bytes']) != (512, 2048, 512, 2048):
        raise ValueError('unexpected sequence extent')
    if source['componentEncoding'] != dict(kindBits=2, componentBits=7, componentShift=2, kinds={'position': 0, 'generic': 1, 'pointSize': 2}):
        raise ValueError('unexpected component encoding')
    source_rules = rules(source['fields'], 128)
    if [f['word'] for f in source['fields'] if f['name'].startswith('components[')] != list(range(64, 128)):
        raise ValueError('incomplete component array')
    out = ['/* Generated by scripts/generate_tessellation_vertex_source_abi.py. */',
           '#ifndef OPENGPU_TESSELLATION_VERTEX_SOURCE_ABI_H', '#define OPENGPU_TESSELLATION_VERTEX_SOURCE_ABI_H', '',
           '#define OPENGPU_GVS_MAGIC 0x47565301u', '#define OPENGPU_GVS_VERSION 1u',
           '#define OPENGPU_GVS_WORDS 128u', '#define OPENGPU_GVS_BYTES 512u',
           '#define OPENGPU_GVS_MAP_FIRST_WORD 64u', '#define OPENGPU_GVS_MAP_COUNT 64u',
           '#define OPENGPU_GVS_SEQUENCE_BASE_WORD 509u', '#define OPENGPU_GVS_SEQUENCE_LIMIT_WORD 510u', '']
    for field in source['fields']:
        if field['name'].startswith('components['):
            continue
        name = re.sub(r'[^A-Za-z0-9]+', '_', field['name']).upper()
        out += [f'#define OPENGPU_GVS_{name}_WORD {field["word"]}u', f'#define OPENGPU_GVS_{name}_BITS {field["bits"]}u']
        if 'constant' in field:
            out += [f'#define OPENGPU_GVS_{name}_VALUE {field["constant"]}u']
    def array(name, values):
        out.extend(['', f'static const unsigned char {name}[{len(values)}] = {{'])
        for i in range(0, len(values), 16):
            out.append('    ' + ', '.join(map(str, values[i:i + 16])) + ',')
        out.append('};')
    array('opengpu_gvs_word_rules', source_rules)
    gnd = json.loads((directory / 'native-binned-graphics-v1.json').read_text())['draw']
    if (gnd['magic'], gnd['words'], gnd['bytes']) != ('0x474e4401', 512, 2048):
        raise ValueError('unexpected original GND1')
    array('opengpu_gvs_draw_word_rules', rules([dict(name=f'header{i}', word=i, bits=32, signed=False) for i in range(3)] + gnd['fields'], 512))
    old = {record['domain']: record for record in uniforms['records']}
    records = sequence['records']
    if [(r['domain'], r['magic'], r['version'], r['uniformVersion']) for r in records] != [
        ('isoline', '0x474e5407', 7, 4), ('triangle', '0x474e5408', 8, 5), ('quad', '0x474e5409', 9, 6)]:
        raise ValueError('wrong exact domain/version pairing')
    if sequence['fields'] != [dict(name='vertexSource.base', word=509, bits=32, signed=False), dict(name='vertexSource.limit', word=510, bits=33, signed=False)]:
        raise ValueError('wrong append-only source range')
    for record in records:
        base = json.loads((directory / old[record['domain']]['baseSchema']).read_text())
        if old[record['domain']]['version'] != record['uniformVersion']:
            raise ValueError('wrong inherited uniform dialect')
        values = rules([dict(name=f'header{i}', word=i, bits=32, signed=False) for i in range(3)] + base['fields'] + uniforms['fields'] + sequence['fields'], 512)
        name = record['domain'].upper()
        out += ['', f'#define OPENGPU_GVS_{name}_SEQUENCE_MAGIC {record["magic"]}u', f'#define OPENGPU_GVS_{name}_SEQUENCE_VERSION {record["version"]}u']
        array('opengpu_gvs_' + record['domain'] + '_word_rules', values)
    out += ['', '#endif', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != result:
            raise SystemExit('GVS1 generated header is stale')
    else:
        OUTPUT.write_text(result)
    print('GVS1 / GNT7-9 ABI: ' + ('checked' if args.check else 'generated'))


if __name__ == '__main__':
    main()

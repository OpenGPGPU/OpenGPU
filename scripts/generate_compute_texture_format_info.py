#!/usr/bin/env python3
"""Generate kernel-safe texture-format policy from the generated GTF1 ABI."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/abi/texture-image-format-v1.json"
OUTPUT = ROOT / "driver/opengpu_compute_texture_format_info.h"


def render():
    schema = json.loads(SOURCE.read_text())
    formats = schema["formats"]
    if schema["count"] != 64 or len(formats) != 64 or [f["id"] for f in formats] != list(range(64)):
        raise ValueError("Texture format IDs must cover 0..63")
    lines = ["/* Generated by scripts/generate_compute_texture_format_info.py; do not edit. */",
             "#ifndef OPENGPU_COMPUTE_TEXTURE_FORMAT_INFO_H", "#define OPENGPU_COMPUTE_TEXTURE_FORMAT_INFO_H",
             "struct opengpu_compute_texture_format_info { unsigned char kind, depth, filterable; };",
             "static const struct opengpu_compute_texture_format_info opengpu_compute_texture_formats[64] = {"]
    for f in formats:
        if f["colorType"] not in (0, 1, 2) or type(f["depth"]) is not bool or type(f["filterable"]) is not bool:
            raise ValueError("Invalid texture format policy")
        lines.append(f'    {{{f["colorType"]}, {int(f["depth"])}, {int(f["filterable"])}}}, /* {f["id"]}: {f["name"]} */')
    return "\n".join(lines + ["};", "#endif", ""])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            raise SystemExit("Compute texture format metadata differs from generated ABI")
    else:
        OUTPUT.write_text(content)
    print("Compute texture format metadata: PASS")


if __name__ == "__main__":
    main()
